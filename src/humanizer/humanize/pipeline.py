@dataclass
class ProgressEvent:
    """One line of the progress stream.

    The five keys `stage`, `status`, `progress`, `detail`, `elapsed` are the
    contract. `round` is additive and safe to ignore. `result` is present on
    exactly one event - `finalize/done` - and is dropped from `as_dict()`
    everywhere else, so a client can render every event the same way and only
    special-case the last.
    """

    stage: str
    status: str
    progress: float
    detail: str
    elapsed: float
    round: int = 1
    result: Optional[Dict[str, Any]] = None
    #: The same result as a dataclass, for in-process callers. Never
    #: serialised: `as_dict()` is the wire format and it carries `result`.
    result_object: Optional[Any] = None

    def as_dict(self) -> Dict[str, Any]:
        payload: Dict[str, Any] = {
            "stage": self.stage,
            "status": self.status,
            "progress": round(float(self.progress), 4),
            "detail": self.detail,
            "elapsed": round(float(self.elapsed), 3),
            "round": self.round,
        }
        if self.result is not None:
            payload["result"] = self.result
        return payload


class _Clock:
    """Monotonic elapsed seconds since the run started."""

    def __init__(self) -> None:
        self.t0 = time.perf_counter()

    def __call__(self) -> float:
        return time.perf_counter() - self.t0


# --------------------------------------------------------------- quality


_SYLLABLE_RE = re.compile(r"[aeiouy]+", re.IGNORECASE)

#: Function words dropped before measuring content overlap. Overlap on "the"
#: and "of" measures nothing; overlap on the nouns and verbs is the point.
_STOPWORDS = frozenset(
    """
    a an and are as at be been being but by can could did do does for from had
    has have he her him his how i if in into is it its may me might most much
    must my no nor not of on or our out over she should so some such than that
    the their them then there these they this those to too under up us was we
    were what when where which while who whom whose why will with would you
    your it's don't
    """.split()
)


def _content_words(text: str) -> "frozenset":
    return frozenset(
        w.lower()
        for w in words(text)
        if len(w) > 2 and w.lower() not in _STOPWORDS
    )


def content_overlap(source: str, candidate: str) -> float:
    """Share of the source's content words that survive into the candidate.

    A blunt proxy for "did this rewrite stay on topic", and deliberately
    asymmetric: it penalises *dropping* the source's content, not adding to it,
    because a rewrite that loses half the source's nouns has lost half the
    document whatever else it did. It is not entailment and it is not a
    semantic similarity model - see `engine`'s docstring on the same point.
    Measured here it separates the two failure modes cleanly: faithful
    candidates land at 0.65-1.00, off-topic ones at 0.01-0.15.
    """
    src = _content_words(source)
    if not src:
        return 1.0
    return len(src & _content_words(candidate)) / len(src)


def _syllables(word: str) -> int:
    """Crude English syllable count: vowel runs, minus a silent final `e`."""
    groups = _SYLLABLE_RE.findall(word)
    n = len(groups)
    if word.lower().endswith("e") and n > 1 and not word.lower().endswith(("le", "ee")):
        n -= 1
    return max(1, n)


def flesch_reading_ease(text: str) -> float:
    """Flesch reading ease, approximately.

    The syllable counter is a vowel-run heuristic, so this is accurate to a few
    points, not exactly. It is used as a **sanity check, not a gate**: the
    question it answers is "did the rewrite quietly turn academic prose into
    listicle prose, or the reverse", and a few points either way does not
    change that answer. Academic prose typically lands 10-40; a large move in
    either direction is worth a flag.
    """
    doc = Document.parse(text)
    sentences = [s for s in doc.sentences if s.words]
    tokens = words(text)
    if not sentences or not tokens:
        return float("nan")
    syllables = sum(_syllables(w) for w in tokens)
    return (
        206.835
        - 1.015 * (len(tokens) / len(sentences))
        - 84.6 * (syllables / len(tokens))
    )


def _quality(source: str, candidate: str) -> Dict[str, Any]:
    """Readability, shape and vocabulary numbers for one candidate."""
    feats = extract_from_document(Document.parse(candidate))
    cv = feats.get("sent_len_cv", float("nan"))
    ease = flesch_reading_ease(candidate)
    source_ease = flesch_reading_ease(source)
    flags: List[str] = []
    if isinstance(cv, float) and math.isfinite(cv) and not (
        HUMAN_SENTENCE_CV[0] <= cv <= HUMAN_SENTENCE_CV[1]
    ):
        flags.append("sent_len_cv_outside_human_band")
    if math.isfinite(ease) and math.isfinite(source_ease) and abs(ease - source_ease) > 20:
        flags.append("readability_shifted")
    overlap = content_overlap(source, candidate)
    if overlap < 0.55:
        # Not a gate at this threshold, a warning: 0.55 is where a rewrite has
        # started paraphrasing nouns away rather than merely restructuring.
        flags.append("possible_semantic_drift")
    # The research/24 structure checks: repeated openers, uniform beats, the
    # paired-coordination template, unhedged absolutes, surface statements.
    structure = kriukow.structure_report(candidate)
    flags.extend(kriukow.structure_flags(structure))
    return {
        "content_overlap": round(overlap, 4),
        "sent_len_cv": None if not math.isfinite(cv) else round(cv, 4),
        "sent_len_mean": round(feats.get("sent_len_mean", float("nan")), 3)
        if math.isfinite(feats.get("sent_len_mean", float("nan")))
        else None,
        "ai_vocab_hits_per_1k": round(feats.get("ai_vocab_hits_per_1k", 0.0), 3),
        "flesch_reading_ease": None if not math.isfinite(ease) else round(ease, 1),
        "structure": {k: v for k, v in structure.items() if k != "opener_classes"},
        "flags": flags,
    }


# ----------------------------------------------------------------- scrubbing


def _scrub(text: str, aggressiveness: str = "strong") -> Tuple[str, List[Edit]]:
    """Run the deterministic transform passes over model output.

    Identical in behaviour to the loop inside `engine.humanize`, minus the two
    detector calls that function makes - which is the entire reason this exists
    separately. Returns `(text, accepted_edits)`; the edits are reported so the
    response can show what the scrub did to the winning candidate.
    """
    cfg = config_for(aggressiveness)
    working = normalize(text or "")
    accepted_all: List[Edit] = []
    for stage in PASSES:
        active = [(name, fn) for name, fn in stage if name in cfg.transforms]
        if not active:
            continue
        stage_doc = Document.parse(working)
        ranked: List[Tuple[int, Edit]] = []
        for rank, (_name, transform) in enumerate(active):
            for edit in transform(stage_doc, cfg):
                ranked.append((rank, edit))
        accepted, _dropped = _gate_edits(stage_doc.text, _resolve_overlaps(ranked))
        working = apply_edits(stage_doc.text, accepted)
        accepted_all.extend(accepted)
    return working, accepted_all


