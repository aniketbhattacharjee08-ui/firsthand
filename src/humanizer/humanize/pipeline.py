def _invariant_failures(source: str, candidate: str, facts: str = "") -> List[str]:
    """The meaning invariants, adapted from span edits to whole rewrites.

    `facts` is the author-supplied material of `PipelineConfig.facts`. A
    number, date, quotation or citation that the source lacks is allowed in
    the candidate only if it appears in `facts`; a source item that vanishes
    is a failure whatever `facts` says. With `facts` empty this is the exact
    multiset comparison it always was.

    `engine.invariants` is reused unchanged for numbers, quotations,
    citations and dates: those are evidence, they are compared as exact
    multisets, and a whole-paragraph rewrite has no more licence to alter one
    than a span edit does.

    **Entities are the one deliberate difference, and it is a correctness fix
    rather than a relaxation.** `engine.invariants` compares the capitalised
    mid-sentence runs of the two texts as *sets*, and `engine._entities` drops
    each sentence's first token because sentence-initial capitalisation is
    orthography, not identity. That is exactly right for a span edit, which
    moves at most one sentence boundary. It is wrong for a rewrite that
    reorders sentences: a name that sat mid-sentence in the source and opens a
    sentence in the candidate is dropped from the candidate's set and the
    source's set keeps it, so a perfectly faithful rewrite reports a corrupted
    entity. Measured on the benchmark corpus this fired on 48 of 84 candidates,
    almost all of them faithful.

    So the entity test here is directional and positional-agnostic: every
    capitalised run the source contains must still appear, verbatim and
    case-sensitively, somewhere in the candidate. That still catches the
    failure the gate exists for - a name vanishing, or being respelled - and it
    stops flagging sentence order as a factual change. It does not object to a
    *new* capitalised run, which a reordering rewrite legitimately produces.
    """
    before, after = invariants(source), invariants(candidate)
    allowed = invariants(facts) if facts and facts.strip() else None
    failures: List[str] = []
    for key in ("numbers", "quotations", "citations", "dates"):
        if before[key] == after[key]:
            continue
        if any(after[key][item] < n for item, n in before[key].items()):
            failures.append(key)  # something the source had is gone or altered
            continue
        extra = after[key] - before[key]
        # A particular the author supplied may be used as often as the rewrite
        # needs; what is refused is a particular that appears nowhere in the
        # facts. (Counting matches made "1 to 3 degrees ... 3 degrees" fail.)
        if allowed is None or any(allowed[key][item] == 0 for item in extra):
            failures.append(key)  # something new that the author did not supply
    if any(entity not in candidate for entity in before["entities"]):
        failures.append("entities")
    return failures


def new_specifics(source: str, candidate: str, facts: str = "") -> List[str]:
    """Numbers and capitalised runs in `candidate` that neither the source
    nor the author's `facts` contain: the material a reader would have to
    verify. Ordered as they appear in the candidate, de-duplicated."""
    before, after = invariants(source), invariants(candidate)
    allowed = invariants(facts) if facts and facts.strip() else None
    out: List[str] = []
    seen: set = set()
    extra_numbers = after["numbers"] - before["numbers"]
    if allowed is not None:
        extra_numbers = Counter({k: v for k, v in extra_numbers.items() if allowed["numbers"][k] == 0})
    # An entity counts as vouched for when it appears verbatim in the facts;
    # `invariants()` would drop a sentence-initial "Dr" from "Dr Jackson".
    entities = {
        e for e in set(after["entities"]) - set(before["entities"])
        if not (allowed is not None and e in facts)
    }
    for match in _NEW_SPECIFIC_RE.finditer(candidate):
        token = match.group(0)
        if token in seen:
            continue
        if extra_numbers.get(token, 0) > 0 or token in entities:
            seen.add(token)
            out.append(token)
    return out


_NEW_SPECIFIC_RE = re.compile(
    _NUMBER_RE.pattern + r"|[A-Z][A-Za-z'’-]*(?:\s+[A-Z][A-Za-z'’-]*)*"
)


def _gate_candidate(
    source: str,
    candidate: str,
    config: PipelineConfig,
) -> List[str]:
    """Names of every gate the candidate fails. Empty means it is usable.

    Every gate is a hard reject. There is no weighting and no score here on
    purpose (research/00 §6): a candidate that changed a number is not a
    slightly worse candidate.
    """
    failures: List[str] = []
    text = (candidate or "").strip()
    if not text:
        return ["empty"]

    n_source = len(words(source))
    n_candidate = len(words(text))
    if n_source == 0:
        return ["empty_source"]

    ratio = n_candidate / n_source
    if abs(ratio - 1.0) > config.max_length_ratio_delta:
        failures.append("length_ratio")
    if ratio < config.min_length_ratio:
        failures.append("too_short")
    if content_overlap(source, text) < config.min_content_overlap:
        failures.append("content_drift")
    for name in _invariant_failures(source, text, getattr(config, "facts", "")):
        failures.append("invariant:" + name)
    if text == source.strip():
        failures.append("unchanged")
    return failures


#: Cap on the specifics named per paragraph in `fallback_reason`.
_MAX_REPORTED_SPECIFICS = 8


def _plural(n: int, word: str) -> str:
    """`3 paragraphs` / `1 paragraph`. `detail` is rendered verbatim in the UI."""
    return "%d %s%s" % (n, word, "" if n == 1 else "s")


def _paragraph_segments(text: str) -> List[str]:
    """Paragraphs, or the whole document as one when it has no blank lines."""
    parts = split_paragraphs(text)
    return parts or ([text.strip()] if text.strip() else [])


def _measure(text: str, detector: Any) -> Dict[str, Any]:
    """The `before`/`after` block: feature vector plus the yardstick's verdict.

    `detector` is the yardstick, never the proxy. When it is a
    `detectors.yardstick.Yardstick` the block also names it, so a reader of
    the response can see whether `ai_probability` is a GPTZero number or a
    local stand-in.
    """
    doc = Document.parse(text)
    probability, label = _score_and_label(text, detector)
    block: Dict[str, Any] = {
        "ai_probability": probability,
        "label": label,
        "features": extract_from_document(doc),
    }
    if isinstance(detector, yardstick_mod.Yardstick):
        block["yardstick"] = {
            "name": detector.name,
            "kind": detector.kind,
            "model": detector.model,
        }
    return block


def _assumed_ai_block(text: str) -> Dict[str, Any]:
    """The `before` block when the input is assumed AI (`assume_ai`).

    Same shape as `_measure` so clients render it the same way, with
    `assumed: True` so a careful client can say "treated as AI" rather than
    "measured as AI". The probability is 1.0 by definition, not by a detector.
    """
    doc = Document.parse(text)
    return {
        "ai_probability": 1.0,
        "label": "ai",
        "assumed": True,
        "features": extract_from_document(doc),
        "yardstick": {"name": "assumed", "kind": "assumption", "model": "every input is treated as AI-written"},
    }


def stream(
    text: str,
    config: Optional[PipelineConfig] = None,
    backend: Optional[llm_mod.Backend] = None,
    detector: Any = None,
) -> Iterator[ProgressEvent]:
    """Run the pipeline, yielding a `ProgressEvent` for every step.

    Args:
        text: the document. Normalised on entry.
        config: see `PipelineConfig`. `None` uses the defaults.
        backend: an `llm.Backend`, used for every style. `None` builds one
            `MlxBackend` per style in `config.styles()`. Tests pass
            `llm.EchoBackend`.
        detector: anything with `.score(text).ai_probability`, used as both
            the yardstick and the candidate scorer. `None` uses
            `detectors.yardstick`: GPTZero for the document verdict when a
            key is configured, the local proxy for candidates. Pass `False`
            to score nothing, which makes every probability null and turns
            selection into "first candidate that passes the gates".

    Yields:
        `ProgressEvent`s in stage order. The final one is `finalize/done` and
        carries `result`.

    Raises:
        ValueError: on empty input.
        RuntimeError: when the backend cannot load. The message names the
            rule-based engine as the fallback.
    """
    if not text or not text.strip():
        raise ValueError("text must not be empty")

    cfg = config or PipelineConfig()
    if cfg.n_candidates <= 0:
        raise ValueError("n_candidates must be positive")
    clock = _Clock()
    stage_timings: List[Dict[str, Any]] = []
    stage_started: Dict[str, float] = {}

    # `det` ranks candidates; `yard` gives the document its verdict. They are
    # the same object unless the yardstick is GPTZero, in which case `det` is
    # the free local proxy -- see `detectors.yardstick` for why.
    yard: Any
    if detector is False:
        det = None
        yard = None
    elif detector is None:
        det = _detector() if cfg.score_candidates else None
        yard = _yardstick()
    else:
        det = detector
        yard = detector

    backends: Dict[str, llm_mod.Backend]
    retry_backend: Optional[llm_mod.Backend] = None
    backend_supplied = backend is not None
    if backend is None:
        backends = {
            s: llm_mod.backend_for(s, cfg.model_for(s)) for s in cfg.styles()
        }
        # The second distribution for stubborn paragraphs (round 3 onward).
        # Only when the pipeline builds its own backends: a caller-supplied
        # backend (tests, the echo backend) is used for every round.
        if cfg.retry_adapter and "freeform" in cfg.styles():
            retry_backend = llm_mod.backend_for(
                "freeform", cfg.model_for("freeform"), cfg.retry_adapter
            )
    else:
        backends = {s: backend for s in cfg.styles()}
    backend = backends[cfg.styles()[0]]

    def event(
        stage: str,
        status: str,
        progress: float,
        detail: str,
        rnd: int = 1,
        result: Optional[Dict[str, Any]] = None,
    ) -> ProgressEvent:
        now = clock()
        if status == "start":
            stage_started[stage] = now
        if status in ("done", "skip"):
            started = stage_started.pop(stage, now)
            stage_timings.append(
                {
                    "stage": stage,
                    "status": status,
                    "seconds": round(now - started, 3),
                    "detail": detail,
                    "round": rnd,
                }
            )
        return ProgressEvent(stage, status, progress, detail, now, rnd, result)

    # -- analyze ----------------------------------------------------------
    yield event("analyze", "start", 0.0, "reading the document")
    original = normalize(text)
    segments = _paragraph_segments(original)
    doc = Document.parse(original)
    yield event(
        "analyze",
        "progress",
        0.4,
        "%s, %s, %s"
        % (
            _plural(len(segments), "paragraph"),
            _plural(doc.n_sentences, "sentence"),
            _plural(doc.n_words, "word"),
        ),
    )
    if cfg.assume_ai:
        before = _assumed_ai_block(original)
        p_before = before["ai_probability"]
        yield event(
            "analyze",
            "done",
            1.0,
            "treating the whole document as AI-written; every paragraph will be rewritten",
        )
    else:
        before = _measure(original, yard)
        p_before = before["ai_probability"]
        yield event(
            "analyze",
            "done",
            1.0,
            "scored the original with %s: %s"
            % (
                _scorer_name(yard),
                "detector unavailable"
                if p_before is None
                else "p(AI) %.3f, labelled %s" % (p_before, before["label"]),
            ),
        )

    # -- plan -------------------------------------------------------------
    yield event("plan", "start", 0.0, "choosing candidates")
    specs = llm_mod.specs_for(cfg.n_candidates, cfg.style)
    total_candidates = len(specs) * len(segments)
    est_tokens = sum(llm_mod.estimate_max_tokens(s) for s in segments) * len(specs)
    yield event(
        "plan",
        "done",
        1.0,
        "%s x %s = %s, up to ~%d generated tokens, about %s"
        % (
            _plural(len(specs), "candidate"),
            _plural(len(segments), "paragraph"),
            _plural(total_candidates, "rewrite"),
            est_tokens,
            _eta_text(est_tokens, len(specs), len(segments), backends.values()),
        ),
    )

    outcomes = [
        ParagraphOutcome(index=i, original=s, chosen=s) for i, s in enumerate(segments)
    ]
    for outcome in outcomes:
        # Under `assume_ai` the paragraph baseline is the assumption itself;
        # nothing of the input is sent to a detector before generation.
        outcome.ai_probability_before = 1.0 if cfg.assume_ai else _score(outcome.original, det)

    generation_seconds = 0.0
    generation_tokens = 0
    used_batching = False
    backend_error: Optional[str] = None

    for rnd in range(1, max(1, cfg.rounds) + 1):
        targets = [
            o
            for o in outcomes
            if rnd == 1
            or (
                o.ai_probability_after is not None
                and o.ai_probability_after >= cfg.pass_threshold
            )
        ]
        if rnd > 1:
            if not targets:
                yield event(
                    "generate",
                    "skip",
                    1.0,
                    "round %d not needed: every paragraph is already below the "
                    "%.2f threshold" % (rnd, cfg.pass_threshold),
                    rnd,
                )
                break
            if clock() > cfg.time_budget_s:
                yield event(
                    "generate",
                    "skip",
                    1.0,
                    "round %d skipped: %.1fs budget already spent"
                    % (rnd, cfg.time_budget_s),
                    rnd,
                )
                break

        # -- generate -----------------------------------------------------
        yield event(
            "generate",
            "start",
            0.0,
            "loading %s" % cfg.resolved_model(),
            rnd,
        )
        try:
            for b in _unique(backends.values()):
                b.load()
        except RuntimeError as exc:
            backend_error = str(exc)
            raise

        fresh: List[Candidate] = []
        skipped_for_budget = 0
        # Paragraphs go to the model in groups, so one batched decode carries
        # `group` paragraphs x `len(specs)` candidates. The decode is
        # memory-bound: eight prompts cost about what four do, so a
        # five-paragraph essay no longer waits five times for the model.
        group = _paragraph_group_size(backends.values(), len(specs))
        n_done = 0
        for g0 in range(0, len(targets), group):
            batch_targets = targets[g0 : g0 + group]
            # Round 1 always finishes every paragraph. The budget only stops
            # later rounds: a paragraph left unrewritten reads to the user as
            # the product having done nothing.
            if rnd > 1 and g0 > 0 and clock() > cfg.time_budget_s:
                skipped_for_budget = len(targets) - g0
                yield event(
                    "generate",
                    "progress",
                    g0 / max(1, len(targets)),
                    "budget spent after paragraph %d of %d; %d left unrewritten"
                    % (g0, len(targets), skipped_for_budget),
                    rnd,
                )
                break
            first, last = g0 + 1, g0 + len(batch_targets)
            which = (
                "paragraph %d of %d" % (first, len(targets))
                if first == last
                else "paragraphs %d-%d of %d" % (first, last, len(targets))
            )
            yield event(
                "generate",
                "progress",
                g0 / max(1, len(targets)),
                "%s, %d candidates in %s"
                % (
                    which,
                    len(specs) * len(batch_targets),
                    "one batch" if len(cfg.styles()) == 1 else "one batch per model",
                ),
                rnd,
            )
            # One batch per style: the instruct and base checkpoints are
            # different backends and `batch_generate` cannot span them.
            para_seconds = 0.0
            para_tps = 0.0
            for style in cfg.styles():
                style_specs = [s for s in specs if s.style == style]
                if not style_specs:
                    continue
                pairs = [(outcome, spec) for outcome in batch_targets for spec in style_specs]
                requests = [
                    llm_mod.GenerationRequest(
                        prompt=llm_mod.build_prompt(outcome.original, spec, facts=cfg.facts),
                        temperature=spec.temperature,
                        max_tokens=llm_mod.estimate_max_tokens(outcome.original),
                        tag=(outcome.index, spec.index),
                    )
                    for outcome, spec in pairs
                ]
                gen_backend = backends[style]
                if style == "freeform" and rnd >= 3 and retry_backend is not None:
                    gen_backend = retry_backend
                batch = gen_backend.generate(requests)
                generation_seconds += batch.seconds
                generation_tokens += batch.generation_tokens
                used_batching = used_batching or batch.batched
                para_seconds += batch.seconds
                para_tps = batch.tokens_per_second
                stops = llm_mod.STOPS_FOR_STYLE.get(style, ())
                for (outcome, spec), raw in zip(pairs, batch.texts):
                    fresh.append(
                        Candidate(
                            paragraph_index=outcome.index,
                            index=spec.index,
                            persona=spec.persona,
                            constraint=spec.constraint,
                            temperature=spec.temperature,
                            round=rnd,
                            raw=llm_mod.clean_completion(raw, stops),
                            style=spec.style,
                        )
                    )
            n_done += len(batch_targets)
            yield event(
                "generate",
                "progress",
                n_done / max(1, len(targets)),
                "%s done in %.1fs (%.0f tok/s)" % (which, para_seconds, para_tps),
                rnd,
            )
        yield event(
            "generate",
            "done",
            1.0,
            "%s in %.1fs, %s"
            % (
                _plural(len(fresh), "candidate"),
                generation_seconds,
                "batched decode" if used_batching else "one at a time",
            ),
            rnd,
        )

        # -- scrub --------------------------------------------------------
        # After the model, never before: the instruct checkpoint reintroduces
        # the vocabulary this pass exists to remove.
        yield event("scrub", "start", 0.0, "applying deterministic transforms", rnd)
        for i, cand in enumerate(fresh):
            cand.scrubbed, cand.scrub_edits = _scrub(cand.raw, cfg.aggressiveness)
            if i % max(1, len(fresh) // 4) == 0 or i == len(fresh) - 1:
                yield event(
                    "scrub",
                    "progress",
                    (i + 1) / max(1, len(fresh)),
                    "candidate %d of %d, paragraph %d of %d"
                    % (
                        cand.index + 1,
                        len(specs),
                        cand.paragraph_index + 1,
                        len(segments),
                    ),
                    rnd,
                )
        n_edits = sum(len(c.scrub_edits) for c in fresh)
        yield event(
            "scrub",
            "done",
            1.0,
            "%s across %s"
            % (_plural(n_edits, "deterministic edit"), _plural(len(fresh), "candidate")),
            rnd,
        )

        # -- score --------------------------------------------------------
        if det is None:
            yield event(
                "score",
                "skip",
                1.0,
                "no detector available; candidates cannot be ranked by score",
                rnd,
            )
        else:
            yield event(
                "score",
                "start",
                0.0,
                "scoring candidates with %s" % _scorer_name(det),
                rnd,
            )
            for i, cand in enumerate(fresh):
                cand.ai_probability = _score(cand.scrubbed, det)
                yield event(
                    "score",
                    "progress",
                    (i + 1) / max(1, len(fresh)),
                    "candidate %d of %d, paragraph %d of %d: %s"
                    % (
                        cand.index + 1,
                        len(specs),
                        cand.paragraph_index + 1,
                        len(segments),
                        "unscored"
                        if cand.ai_probability is None
                        else "p(AI) %.3f" % cand.ai_probability,
                    ),
                    rnd,
                )
            yield event(
                "score",
                "done",
                1.0,
                "scored %d candidates" % len(fresh),
                rnd,
            )

        # -- verify -------------------------------------------------------
        yield event("verify", "start", 0.0, "checking hard gates", rnd)
        by_paragraph: Dict[int, List[Candidate]] = {}
        for i, cand in enumerate(fresh):
            source = outcomes[cand.paragraph_index].original
            cand.gates = _gate_candidate(source, cand.scrubbed, cfg)
            cand.quality = _quality(source, cand.scrubbed) if cand.scrubbed else {}
            by_paragraph.setdefault(cand.paragraph_index, []).append(cand)
            yield event(
                "verify",
                "progress",
                (i + 1) / max(1, len(fresh)),
                "candidate %d of %d, paragraph %d of %d: %s"
                % (
                    cand.index + 1,
                    len(specs),
                    cand.paragraph_index + 1,
                    len(segments),
                    "passed" if cand.passed else "rejected (%s)" % ", ".join(cand.gates),
                ),
                rnd,
            )
        n_passed = sum(1 for c in fresh if c.passed)
        yield event(
            "verify",
            "done",
            1.0,
            "%d of %d candidates passed every gate" % (n_passed, len(fresh)),
            rnd,
        )

        # -- select -------------------------------------------------------
        yield event("select", "start", 0.0, "ranking survivors", rnd)
        for n, (para_index, cands) in enumerate(sorted(by_paragraph.items())):
            outcome = outcomes[para_index]
            outcome.candidates.extend(cands)
            survivors = [c for c in cands if c.passed]
            if not survivors:
                # Owner's rule since 2026-09-22: every paragraph ships a
                # rewrite. Gates now order the fallbacks instead of vetoing
                # them: fewest failures first (a length-band miss over a
                # drift, a drift over an invented figure), then the lowest
                # scorer probability. The one thing still refused is junk, a
                # candidate empty or under `_JUNK_LENGTH_RATIO` of the source,
                # because "No." is not a rewrite of anything.
                real = [c for c in cands if _is_real_rewrite(outcome.original, c)]
                reasons = sorted({g for c in cands for g in c.gates})
                if any(g.startswith("invariant:") for g in reasons):
                    ranked = sorted(
                        cands,
                        key=lambda c: c.ai_probability if c.ai_probability is not None else 1.0,
                    )
                    specifics: List[str] = []
                    for c in ranked:
                        for item in new_specifics(outcome.original, c.scrubbed, cfg.facts):
                            if item not in specifics:
                                specifics.append(item)
                        if len(specifics) >= _MAX_REPORTED_SPECIFICS:
                            break
                    outcome.unverified_specifics = specifics[:_MAX_REPORTED_SPECIFICS]
                if real:
                    best = min(real, key=lambda c: _fallback_key(c, cfg))
                    outcome.chosen = best.scrubbed
                    outcome.chosen_index = best.index
                    outcome.ai_probability_after = best.ai_probability
                    outcome.fallback_reason = (
                        "no candidate passed every gate (%s); shipped the closest "
                        "rewrite anyway, which missed %s"
                        % (", ".join(reasons), ", ".join(sorted(best.gates)) or "nothing")
                    )
                    if outcome.unverified_specifics:
                        outcome.fallback_reason += (
                            "; rewrites added material the draft does not contain (%s)"
                            % ", ".join(outcome.unverified_specifics)
                        )
                    yield event(
                        "select",
                        "progress",
                        (n + 1) / max(1, len(by_paragraph)),
                        "paragraph %d of %d: no clean survivor, candidate %d shipped "
                        "anyway (%s)"
                        % (
                            para_index + 1,
                            len(segments),
                            best.index + 1,
                            "unscored"
                            if best.ai_probability is None
                            else "p(AI) %.3f" % best.ai_probability,
                        ),
                        rnd,
                    )
                    continue
                outcome.fallback_reason = (
                    "every candidate was junk (%s); kept the original" % ", ".join(reasons)
                )
                yield event(
                    "select",
                    "progress",
                    (n + 1) / max(1, len(by_paragraph)),
                    "paragraph %d of %d: all %d candidates were junk, keeping the "
                    "original" % (para_index + 1, len(segments), len(cands)),
                    rnd,
                )
                continue
            scored = [c for c in survivors if c.ai_probability is not None]
            if scored:
                # Evasion first: the score is the objective. `quality_weight`
                # is the knob that slowly reintroduces the writing bands; at
                # its default of 0.0 this is a pure argmin over the proxy.
                best = min(scored, key=lambda c: _rank_key(c, cfg))
            else:
                # No detector: rank by the free writing heuristics (sentence
                # length band, structure template penalty, a little drift).
                # Ties go to the earlier (more conservative) candidate.
                best = min(survivors, key=lambda c: (_heuristic_key(c), c.index))
            baseline = (
                outcome.ai_probability_after
                if outcome.ai_probability_after is not None
                else outcome.ai_probability_before
            )
            if (
                best.ai_probability is not None
                and baseline is not None
                and best.ai_probability >= baseline
                and rnd > 1
            ):
                # A refinement round may not make a paragraph worse.
                outcome.fallback_reason = (
                    "round %d produced nothing better than round %d" % (rnd, rnd - 1)
                )
            else:
                outcome.chosen = best.scrubbed
                outcome.chosen_index = best.index
                outcome.ai_probability_after = best.ai_probability
                outcome.fallback_reason = None
            yield event(
                "select",
                "progress",
                (n + 1) / max(1, len(by_paragraph)),
                "paragraph %d of %d: candidate %d wins (%s), %d of %d survived"
                % (
                    para_index + 1,
                    len(segments),
                    best.index + 1,
                    "unscored"
                    if best.ai_probability is None
                    else "p(AI) %.3f" % best.ai_probability,
                    len(survivors),
                    len(cands),
                ),
                rnd,
            )
        yield event(
            "select",
            "done",
            1.0,
            "%d of %s rewritten"
            % (
                sum(1 for o in outcomes if o.changed),
                _plural(len(outcomes), "paragraph"),
            ),
            rnd,
        )

    # -- repair -----------------------------------------------------------
    # The self-correcting stage. Imported here rather than at module level
    # because `repair` reuses this module's gates and scrubber and imports it.
    from . import repair as repair_mod

    repair_summary = yield from repair_mod.run_repairs(
        outcomes,
        cfg,
        backends=backends,
        det=det,
        clock=clock,
        event=event,
        retry_backend=retry_backend,
        caller_backend=backend if backend_supplied else None,
        rounds_run=max(1, cfg.rounds),
    )

    # -- finalize ---------------------------------------------------------
    yield event("finalize", "start", 0.0, "reassembling and re-measuring")
    humanized = "\n\n".join(o.chosen.strip() for o in outcomes if o.chosen.strip())
    after = _measure(humanized, yard)
    p_after = after["ai_probability"]
    all_candidates = [c for o in outcomes for c in o.candidates]
    winning_edits = [
        e
        for o in outcomes
        for c in o.candidates
        if c.index == o.chosen_index and c.paragraph_index == o.index
        for e in c.scrub_edits
    ]
    summary = {
        "engine": "llm",
        "model": cfg.resolved_model(),
        "models": {s: cfg.model_for(s) for s in cfg.styles()},
        "backend": getattr(backend, "name", ""),
        "style": cfg.style,
        "objective": cfg.objective,
        "quality_weight": cfg.quality_weight,
        "gates": {
            "min_content_overlap": cfg.min_content_overlap,
            "max_length_ratio_delta": cfg.max_length_ratio_delta,
            "min_length_ratio": cfg.min_length_ratio,
        },
        # Which model produced each reported number. `yardstick` is the
        # verdict; `candidate_scorer` ranked the candidates. They differ
        # only when the yardstick is GPTZero.
        "yardstick": yard.describe() if isinstance(yard, yardstick_mod.Yardstick) else (
            {"name": _scorer_name(yard), "kind": "caller-supplied"} if yard is not None else None
        ),
        "candidate_scorer": _scorer_name(det) if det is not None else None,
        "winning_styles": {
            s: sum(
                1
                for o in outcomes
                for c in o.candidates
                if c.index == o.chosen_index and c.paragraph_index == o.index and c.style == s
            )
            for s in cfg.styles()
        },
        "n_edits": len(winning_edits),
        "n_paragraphs": len(outcomes),
        "n_candidates_total": len(all_candidates),
        "n_candidates_passed": sum(1 for c in all_candidates if c.passed),
        "n_candidates_rejected": sum(1 for c in all_candidates if not c.passed),
        "gate_rejections": _rejection_counts(all_candidates),
        "paragraphs_rewritten": sum(1 for o in outcomes if o.changed),
        "paragraphs_unchanged": sum(1 for o in outcomes if not o.changed),
        "facts_supplied": bool(cfg.facts and cfg.facts.strip()),
        # Union over paragraphs, in order, of what the rejected best candidates
        # invented. Empty when facts were supplied and used, or when nothing
        # was rejected on an invariant.
        "unverified_specifics": _unique_in_order(
            item for o in outcomes for item in o.unverified_specifics
        )[:_MAX_REPORTED_SPECIFICS * 2],
        "risk_delta": None
        if (p_before is None or p_after is None)
        else round(p_after - p_before, 6),
        "label_before": before.get("label"),
        "before_assumed": bool(before.get("assumed")),
        "label_after": after.get("label"),
        "verdict_flipped": bool(
            before.get("label") == "ai" and after.get("label") == "human"
        ),
        "seconds": round(clock(), 3),
        "generation_seconds": round(generation_seconds, 3),
        "generation_tokens": generation_tokens,
        # Guarded on a floor rather than on zero: a backend that returns
        # instantly (the test double, a cache hit) would otherwise report a
        # throughput in the millions, which is worse than reporting nothing.
        "tokens_per_second": round(generation_tokens / generation_seconds, 1)
        if generation_seconds > 0.05
        else None,
        "batched": used_batching,
        "quality_flags": _rejection_counts_from_flags(all_candidates),
        "backend_error": backend_error,
        # The repair stage: how many diagnose-and-retry attempts ran, how
        # many produced an accepted rewrite, and the per-attempt log.
        "repairs_attempted": repair_summary["attempted"],
        "repairs_accepted": repair_summary["accepted"],
        "repairs_rescued": repair_summary["rescued"],
        "repair_log": repair_summary["log"],
    }
    result = LlmHumanizeResult(
        original=original,
        humanized=humanized,
        model=cfg.resolved_model(),
        backend=getattr(backend, "name", ""),
        before=before,
        after=after,
        summary=summary,
        paragraphs=outcomes,
        stages=stage_timings,
        edits=winning_edits,
    )
    detail = "%s in %.1fs" % (
        "verdict flipped ai -> human"
        if summary["verdict_flipped"]
        else "verdict unchanged (%s)" % (after.get("label") or "unscored"),
        summary["seconds"],
    )
    # The finalize timing is appended by hand rather than through `event()` so
    # that it is already in `stage_timings` when the payload is built. A
    # `stages` list that is missing its own last row is the kind of small lie
    # that makes a timing table useless.
    now = clock()
    stage_timings.append(
        {
            "stage": "finalize",
            "status": "done",
            "seconds": round(now - stage_started.pop("finalize", now), 3),
            "detail": detail,
            "round": 1,
        }
    )
    payload = result.as_dict()
    yield ProgressEvent(
        stage="finalize",
        status="done",
        progress=1.0,
        detail=detail,
        elapsed=now,
        round=1,
        result=payload,
        result_object=result,
    )


def _rank_key(candidate: Candidate, cfg: PipelineConfig) -> float:
    """Lower is better. Proxy probability plus a weighted quality penalty.

    The penalty is in the same units as the probability so `quality_weight`
    reads as "how many points of AI probability I would pay for a candidate
    that sits in the human bands". It has two terms, each in [0, 1]: distance
    of the sentence-length CV from the research/10 band, and the share of
    the source's content words the candidate dropped. At weight 0 the key is
    the probability alone, which is the `evade` default.
    """
    p = candidate.ai_probability if candidate.ai_probability is not None else 1.0
    w = float(cfg.quality_weight or 0.0)
    if w <= 0.0:
        return p
    cv_term = min(1.0, _cv_distance(candidate))
    if not math.isfinite(cv_term):
        cv_term = 1.0
    overlap = candidate.quality.get("content_overlap")
    drift_term = 1.0 - float(overlap) if overlap is not None else 0.0
    # Third term: the research/24 structure penalty (repeated openers, uniform
    # beats, paired-coordination template, unhedged absolutes, surface
    # statements), already in [0, 1].
    structure = candidate.quality.get("structure") or {}
    structure_term = float(structure.get("penalty", 0.0) or 0.0)
    return p + w * (cv_term + drift_term + structure_term) / 3.0


def _scorer_name(detector: Any) -> str:
    """A short name for whatever is scoring, for progress details."""
    if detector is None:
        return "nothing"
    if isinstance(detector, yardstick_mod.Yardstick):
        return detector.model if detector.kind == "gptzero" else detector.name
    for attr in ("model_name", "name"):
        value = getattr(detector, attr, None)
        if isinstance(value, str) and value:
            return value
    return type(detector).__name__


def _unique(items: Any) -> List[Any]:
    """Distinct objects by identity, in first-seen order."""
    seen: List[Any] = []
    for item in items:
        if not any(item is s for s in seen):
            seen.append(item)
    return seen


#: Gate failures a paragraph may be shipped with when nothing passed cleanly.
_SOFT_GATES = frozenset({"length_ratio"})
#: Below this share of the source's length a candidate is not a rewrite but
#: a refusal or a fragment, and is the one thing the fallback still declines.
_JUNK_LENGTH_RATIO = 0.35


def _is_real_rewrite(source: str, candidate: Candidate) -> bool:
    """True when the candidate is long enough to be a rewrite of `source`."""
    text = (candidate.scrubbed or "").strip()
    if not text:
        return False
    return len(text) >= _JUNK_LENGTH_RATIO * max(1, len(source.strip()))


def _fallback_key(candidate: Candidate, cfg: "PipelineConfig") -> Tuple[int, int, float, int]:
    """Order for candidates that failed a gate: least bad first.

    Invented specifics are the worst failure (a fabricated figure in an essay),
    then any other hard gate, then the scorer's probability, then the earlier
    (more conservative) candidate.
    """
    invariants = sum(1 for g in candidate.gates if g.startswith("invariant:"))
    hard = sum(1 for g in candidate.gates if g not in _SOFT_GATES)
    p = candidate.ai_probability if candidate.ai_probability is not None else 1.0
    return (invariants, hard, _rank_key(candidate, cfg) if candidate.ai_probability is not None else p, candidate.index)

#: Aggregate generated tokens per second to assume for the wait estimate.
#: 21 tok/s was measured for six 7B candidates in one batch (2026-09-20).
_ESTIMATED_TOKENS_PER_S = float(os.environ.get("HUMANIZER_EST_TOKENS_PER_S") or 20.0)
#: Seconds a cold model load adds to the estimate.
_ESTIMATED_LOAD_S = 12.0


def _paragraph_group_size(backends: Any, n_specs: int) -> int:
    """How many paragraphs share one generation batch.

    Bounded by the smallest `max_batch` among the backends so the batched
    decode still fits; backends without one (the echo backend) get one
    paragraph per call, which keeps request order identical to the old loop.
    """
    caps = [int(getattr(b, "max_batch", 0) or 0) for b in backends]
    caps = [c for c in caps if c > 0]
    if not caps or n_specs <= 0:
        return 1
    return max(1, min(caps) // n_specs)


def _eta_text(est_tokens: int, n_specs: int, n_paragraphs: int, backends: Any) -> str:
    """`about 1 min 40 s`: the wait the plan stage announces.

    Tokens over the assumed aggregate rate, plus a load penalty when no
    backend has its weights resident. Rendered verbatim in the UI note.
    """
    seconds = est_tokens / max(1.0, _ESTIMATED_TOKENS_PER_S)
    if not any(getattr(b, "loaded", False) for b in backends):
        seconds += _ESTIMATED_LOAD_S
    seconds = max(5.0, seconds)
    if seconds < 60:
        return "%d s" % (int(seconds / 5.0 + 0.999) * 5)
    minutes, rest = divmod(int(seconds + 0.5), 60)
    rest = int(rest / 10.0 + 0.5) * 10
    if rest >= 60:
        minutes, rest = minutes + 1, 0
    return "%d min" % minutes if rest == 0 else "%d min %d s" % (minutes, rest)


def _heuristic_key(candidate: Candidate) -> float:
    """Lower is better; ranking when no detector scored the candidates.

    The three free terms `_rank_key` weights against the probability, minus
    the probability: distance from the human sentence-length band, the
    research/24 structure penalty, and a quarter weight on content drift so a
    rewrite that kept the source's content words wins a tie but a close copy
    does not beat a better-paced rewrite.
    """
    cv_term = min(1.0, _cv_distance(candidate))
    if not math.isfinite(cv_term):
        cv_term = 1.0
    overlap = candidate.quality.get("content_overlap")
    drift_term = 1.0 - float(overlap) if overlap is not None else 0.0
    structure = candidate.quality.get("structure") or {}
    structure_term = float(structure.get("penalty", 0.0) or 0.0)
    return cv_term + structure_term + 0.25 * drift_term


def _cv_distance(candidate: Candidate) -> float:
    """Distance from the human sentence-length CV band. Ranking fallback."""
    cv = candidate.quality.get("sent_len_cv")
    if cv is None:
        return float("inf")
    lo, hi = HUMAN_SENTENCE_CV
    if cv < lo:
        return lo - cv
    if cv > hi:
        return cv - hi
    return 0.0


def _rejection_counts_from_flags(candidates: Sequence[Candidate]) -> Dict[str, int]:
    """How many candidates carried each quality flag.

    Quality flags are advisory, not gates: `possible_semantic_drift` on a
    candidate that passed every gate is exactly the "fluent but wrong" case the
    brief asks to be surfaced rather than silently shipped.
    """
    counts: Dict[str, int] = {}
    for cand in candidates:
        for flag in cand.quality.get("flags", ()):
            counts[flag] = counts.get(flag, 0) + 1
    return dict(sorted(counts.items()))


def _unique_in_order(items: Any) -> List[str]:
    seen: set = set()
    out: List[str] = []
    for item in items:
        if item not in seen:
            seen.add(item)
            out.append(item)
    return out


def _rejection_counts(candidates: Sequence[Candidate]) -> Dict[str, int]:
    """How many candidates each gate rejected. Reported, never hidden."""
    counts: Dict[str, int] = {}
    for cand in candidates:
        for gate in cand.gates:
            counts[gate] = counts.get(gate, 0) + 1
    return dict(sorted(counts.items()))


def humanize_llm(
    text: str,
    config: Optional[PipelineConfig] = None,
    backend: Optional[llm_mod.Backend] = None,
    detector: Any = None,
    on_event: Optional[Callable[[ProgressEvent], None]] = None,
) -> LlmHumanizeResult:
    """Blocking wrapper over `stream()`.

    Drains the event stream and returns the result. `on_event` is called for
    every event as it happens, which is how a caller that wants both the
    progress and the object gets them without re-running the pipeline.
    """
    final: Optional[LlmHumanizeResult] = None
    for ev in stream(text, config=config, backend=backend, detector=detector):
        if on_event is not None:
            on_event(ev)
        if ev.result_object is not None:
            final = ev.result_object
    if final is None:  # pragma: no cover - stream always ends with finalize
        raise RuntimeError("pipeline produced no result")
    return final
