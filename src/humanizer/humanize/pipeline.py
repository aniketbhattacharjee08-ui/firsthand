"""The LLM humanizing pipeline: generate, scrub, score, gate, select.

This is the orchestrator. `llm.py` knows how to turn a paragraph into prompts;
`transforms.py` and `engine.py` know how to make deterministic edits and how to
check that an edit did not change a fact; `detectors.local.ModernDetector`
knows how to score. This module is the only thing that knows the *order*, and
the order is the design.

The order, and why each step is where it is
-------------------------------------------
::

    analyze -> plan -> generate -> scrub -> score -> verify -> select -> repair -> finalize

**Segment first.** Paragraph by paragraph, so a long document stays inside the
time budget, each rewrite is independently verifiable against its own source,
and a paragraph whose candidates all fail can fall back to its original without
poisoning the rest of the document.

**Generate N diverse candidates.** research/08: correlated candidates make
best-of-N decay as a power law rather than exponentially, so the diversity has
to be engineered. It comes from a different persona and a different structural
instruction per candidate (`llm.CANDIDATE_SPECS`), with temperature varying
underneath. Temperature alone was measured here to buy almost nothing.

**Scrub after the model, never before.** The measured reason: asked to
humanize, Qwen2.5-3B-Instruct returns text still containing "rapidly evolving
digital landscape", "pivotal", "multifaceted", "robust" and "Consequently". The
fingerprint comes from instruction tuning (research/04), so the model
*reintroduces* exactly the vocabulary the deterministic pass removes. Scrubbing
the input and then generating would throw the work away. `_scrub()` runs the
same three transform passes `engine.humanize` runs, under the same meaning
gate, on the model's output.

**Score, then gate, then rank.** Gates are hard rejections, not soft weights
(research/00 §6, research/05 §6). A candidate that mangles a number is not a
slightly worse candidate, it is not a candidate. The gates are:

* every number, date, quotation, citation and named entity preserved exactly
  (`engine.invariants`, reused rather than reimplemented -- see
  `_invariant_failures` for the one deliberate difference). A candidate may
  *add* a number, date, quotation or citation only if the author supplied it
  in `PipelineConfig.facts`; anything else new is refused and named in
  `unverified_specifics`, because the register adapter was measured inventing
  figures in 6 of 6 candidates on 9 of 9 bench paragraphs;
* length ratio within ±25% of the source paragraph;
* no candidate shorter than 70% of the source;
* content-word overlap with the source at or above `min_content_overlap`.

That last one is not in the brief's list and it is the one that does the most
work. Without it the pipeline reports a triumphant score drop for text that has
quietly changed subject - see "What this actually achieves" below.

**Select the best surviving candidate**, or fall back to the paragraph's
original text when none survives. Falling back is reported, never hidden:
`summary["paragraphs_unchanged"]` and each paragraph's `fallback_reason` say so.

What this actually achieves, measured
-------------------------------------
**Against GPTZero itself (2026-09-07 evening, research/24 §6).** With a key
present the yardstick is GPTZero, `HUMANIZER_PROXY=gptzero` makes it the
candidate scorer, and the default `freeform` style (base checkpoint, three
exemplar triples, the author's facts as NOTES) passed **7 of 9** AI bench
paragraphs as human through every gate, 0 of 5 human paragraphs harmed. Every
instruct-model path, including the register LoRA that flips all four local
detectors, scored 1.000 on GPTZero. The table below is the older local-proxy
measurement of the instruct path and is kept as the record of why it was
abandoned as the default.

Measured on an M4 Pro against `desklib/ai-text-detector-v1.01`, over 9 AI
paragraphs (3 hand-written in the stereotypical register, 6 generated by
Qwen2.5-3B-Instruct) and 5 human PMC paragraphs, at 6 candidates per paragraph:

===========================  ==========  ===========  =============
metric                       source      LLM path     rule-based
===========================  ==========  ===========  =============
verdict flips (ai -> human)  --          **0 of 9**   **0 of 9**
mean p(AI)                   1.0000      0.9998       1.0000
mean AI vocabulary per 1k    31.3        13.7         14.9
mean sentence-length CV      0.232       0.304        0.219
in the 0.42-0.60 CV band     0 of 9      0 of 9       0 of 9
mean wall clock              --          12.4 s       < 0.1 s
===========================  ==========  ===========  =============

**It does not flip the verdict, and neither does the rule-based engine.** Say
that plainly rather than quoting the probability drop, which is 0.0001 and
means nothing. research/13's DUPE result is the same shape: attacks that halved
false-negative rates still produced 1 "Human" verdict in 400.

The reason is not a tuning failure, it is a measurement. Three things were
tried and all three landed in the same place:

1. Sampling. Six completions of one prompt at temperatures from 0.7 to 2.0,
   with `top_p` and `min_p` variants: every one scored 1.0000.
2. Prompting. Personas, structural constraints, a banned-vocabulary list, a
   human style exemplar and a hard style contract: faithful candidates score
   0.9996-1.0000.
3. The base checkpoint (`style="freeform"`), which research/05 §6 predicts
   should not carry the instruction-tuning fingerprint. It does produce
   candidates scoring 0.02-0.43 - and every one of them has a content-word
   overlap with the source of 0.01 to 0.15. They are fluent text about a
   different subject. Across the same 14 samples, 3 of 84 freeform candidates
   passed the gates and none of the three lowered the score.

The controlling measurement is simpler than any of those: asked to paraphrase
genuine human PMC paragraphs scoring 0.02-0.24, this model returns text scoring
0.73-1.00. Passing text through a 3B instruct model *makes it look generated*,
whatever the prompt says. Best-of-N cannot select its way out of that, because
the property is in every candidate.

So the honest summary is: **at 3B, on this detector, evasion is available only
in exchange for meaning, and this pipeline is configured to refuse that trade.**
What it does deliver, with meaning gated, is the stylometric half of research/00
§4 - AI vocabulary per 1,000 words from 31.3 to 13.7, sentence-length CV from
0.232 toward the band - and both numbers are in the response next to the
verdict, so nobody has to take the flattering one on faith.

The human-text safety check passed: over 5 genuine PMC paragraphs none crossed
to "ai", the largest movement was -0.0438 (an improvement), and 4 of the 5 were
returned untouched because every candidate failed a gate.

2026-09-07: the priority order was reversed, and the yardstick changed
------------------------------------------------------------------------
Everything above was measured with meaning gated first and desklib as the
judge. The product goal is the other way round: **pass the detector first,
then slowly improve the writing**, and the detector to pass is GPTZero. Three
things changed, all of them configuration rather than new machinery:

1. **The yardstick is `detectors.yardstick`.** GPTZero when `GPTZERO_API_KEY`
   is set, otherwise a named local proxy that the response labels as such.
   Candidates are ranked by the free local proxy; only the document's
   before/after verdict is bought from GPTZero (research/07 §7: validator,
   not inner-loop reward). `summary["yardstick"]` says which one produced the
   number you are reading.
2. **`PipelineConfig.objective` defaults to `"evade"`.** The factual
   invariants stay hard. The three stylistic gates widen (`GATE_PRESETS`),
   selection is a pure argmin over the proxy score, and `quality_weight` is
   the knob that reintroduces the writing bands a little at a time.
3. **`style` defaults to `"mixed"`.** Half the candidates come from the base
   checkpoint, which research/13 §2 puts at 96-99% human on GPTZero for the
   same model family, and which was previously losing only on the content
   gate that `evade` relaxes. The style contract and `llm.CANDIDATE_SPECS`
   gained sentence-structure rules (openers, length runs, tricolons) taken
   from GPTZero's own published cadence heuristics (research/06 §1, §6).

The measured table above is now the *baseline* the `evade` objective is
benchmarked against (`scripts/bench_evasion.py`), not a description of the
current default.

Progress events
---------------
`stream()` is a generator of `ProgressEvent`. Stage names are stable and are
the frontend's checkbox list::

    analyze plan generate scrub score verify select repair finalize

`repair` runs once, after the last round, for every paragraph still failing:
it diagnoses why (from the gate counts and judge scores already in hand),
picks one action from a ladder and retries, recording each attempt on the
paragraph as `repairs`. See `repair.py`.

`status` is one of `start`, `progress`, `done`, `skip`. `progress` is 0.0-1.0
and is non-decreasing within a stage occurrence. `detail` is written to be
shown to a person: "candidate 3 of 6, paragraph 2 of 4". When a refinement
round runs, the stages repeat with `round` incremented; within each occurrence
progress still runs 0 to 1.

The final event is always `finalize/done` and it alone carries `result`, the
full payload.
"""

