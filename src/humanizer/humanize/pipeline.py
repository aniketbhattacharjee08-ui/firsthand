@dataclass
class Candidate:
    """One rewrite of one paragraph, with everything measured about it."""

    paragraph_index: int
    index: int
    persona: str
    constraint: str
    temperature: float
    round: int = 1
    raw: str = ""
    scrubbed: str = ""
    scrub_edits: List[Edit] = field(default_factory=list)
    #: The *candidate scorer's* number (the local proxy), not the yardstick's.
    #: Kept under this name for the frontend; `as_dict` also emits it as
    #: `proxy_probability` so the distinction is visible on the wire.
    ai_probability: Optional[float] = None
    gates: List[str] = field(default_factory=list)
    quality: Dict[str, Any] = field(default_factory=dict)
    style: str = "faithful"

    @property
    def passed(self) -> bool:
        return not self.gates

    def as_dict(self, with_text: bool = True) -> Dict[str, Any]:
        payload: Dict[str, Any] = {
            "paragraph_index": self.paragraph_index,
            "index": self.index,
            "persona": self.persona,
            "constraint": self.constraint,
            "temperature": self.temperature,
            "style": self.style,
            "round": self.round,
            "ai_probability": self.ai_probability,
            "proxy_probability": self.ai_probability,
            "gates": list(self.gates),
            "passed": self.passed,
            "quality": self.quality,
            "n_scrub_edits": len(self.scrub_edits),
        }
        if with_text:
            payload["text"] = self.scrubbed
        return payload


@dataclass
class ParagraphOutcome:
    """What happened to one paragraph."""

    index: int
    original: str
    chosen: str
    chosen_index: Optional[int] = None
    ai_probability_before: Optional[float] = None
    ai_probability_after: Optional[float] = None
    candidates: List[Candidate] = field(default_factory=list)
    fallback_reason: Optional[str] = None
    #: When every candidate was rejected: the numbers and names the
    #: best-scoring rejected candidates introduced that neither the draft nor
    #: `PipelineConfig.facts` contains. The UI shows these so the author can
    #: supply the true ones (or see that the model was inventing).
    unverified_specifics: List[str] = field(default_factory=list)
    #: The repair stage's log for this paragraph, one record per attempt:
    #: `{"attempt", "diagnosis", "action", "result": {"passed", "best",
    #: "accepted"}}` plus `critic` when the LLM critic ran. Empty when the
    #: paragraph passed in the normal rounds or the stage was disabled.
    repairs: List[Dict[str, Any]] = field(default_factory=list)

    @property
    def changed(self) -> bool:
        return self.chosen.strip() != self.original.strip()

    def as_dict(self) -> Dict[str, Any]:
        return {
            "index": self.index,
            "original": self.original,
            "humanized": self.chosen,
            "winning_candidate": self.chosen_index,
            "ai_probability_before": self.ai_probability_before,
            "ai_probability_after": self.ai_probability_after,
            "changed": self.changed,
            "fallback_reason": self.fallback_reason,
            "unverified_specifics": list(self.unverified_specifics),
            "repairs": [dict(r) for r in self.repairs],
            "candidates": [c.as_dict() for c in self.candidates],
        }


@dataclass
class LlmHumanizeResult:
    """The full result. `as_dict()` is the HTTP response body."""

    original: str
    humanized: str
    model: str
    backend: str = ""
    before: Dict[str, Any] = field(default_factory=dict)
    after: Dict[str, Any] = field(default_factory=dict)
    summary: Dict[str, Any] = field(default_factory=dict)
    paragraphs: List[ParagraphOutcome] = field(default_factory=list)
    stages: List[Dict[str, Any]] = field(default_factory=list)
    edits: List[Edit] = field(default_factory=list)

    @property
    def changed(self) -> bool:
        return self.humanized != self.original

    def as_dict(self) -> Dict[str, Any]:
        """The POST /api/humanize/llm body.

        A superset of `HumanizeResult.as_dict()` - `original`, `humanized`,
        `edits`, `before`, `after`, `summary` mean exactly what they mean on
        `POST /api/humanize` - plus `model`, `stages` and `paragraphs`.

        `edits` is the deterministic scrub applied to the **winning
        candidates**, not a diff between the original and the output. The LLM
        rewrite is not expressible as a span edit list, so there is nothing
        honest to put there for it; `paragraphs[i].original` and
        `paragraphs[i].humanized` are the before/after a caller should diff.
        """
        return {
            "original": self.original,
            "humanized": self.humanized,
            "edits": [e.as_dict() for e in self.edits],
            "before": self.before,
            "after": self.after,
            "summary": self.summary,
            "model": self.model,
            "backend": self.backend,
            "stages": list(self.stages),
            "paragraphs": [p.as_dict() for p in self.paragraphs],
        }


OBJECTIVE_EVADE = "evade"
OBJECTIVE_FAITHFUL = "faithful"

#: The stylistic gates per objective. The factual invariants are not here
#: because they are not adjustable: a rewrite that changes a number is wrong
#: under every objective.
#:
#: `evade` widens content overlap to 0.25 because the measured off-topic
#: failure sits at 0.01-0.15 and faithful restructurings at 0.65-1.00, so
#: 0.25 still separates them, and because the base-model candidates GPTZero
#: reads as human cluster at 0.20-0.36 while the ones it reads as AI sit at
#: 0.75-0.85 (research/24 §6.7: on the urban-heat paragraph six of eight
#: candidates were GPTZero-human and every one of them failed at 0.30). It
#: widens length to -45%/+40% for the same reason (the human-rated ones run
#: short) and because research/06 §3 (Perkins) puts paragraph-length
#: variation inside the one structural lever with a peer-reviewed effect on
#: GPTZero. `faithful` is untouched.
GATE_PRESETS: Dict[str, Dict[str, float]] = {
    OBJECTIVE_EVADE: {
        "min_content_overlap": 0.25,
        "max_length_ratio_delta": 0.45,
        "min_length_ratio": 0.55,
    },
    OBJECTIVE_FAITHFUL: {
        "min_content_overlap": 0.45,
        "max_length_ratio_delta": 0.25,
        "min_length_ratio": 0.70,
    },
}


def _default_pass_threshold() -> float:
    """0.5 under GPTZero, 0.15 under the free surrogate, or the env override."""
    raw = os.environ.get("HUMANIZER_PASS_THRESHOLD")
    if raw:
        return float(raw)
    try:
        scorer = yardstick_mod._proxy_name()
    except Exception:  # noqa: BLE001 - a config default must never raise
        scorer = ""
    return 0.5 if scorer == "gptzero" else 0.15


@dataclass
class PipelineConfig:
    """Everything tunable about one run.

    `time_budget_s` is a soft budget: it is checked between paragraphs and
    between rounds, never mid-generation, so one paragraph can overshoot it.
    30 seconds is the user-accepted figure and is roughly 1800 generated tokens
    at the measured single-stream rate, or six paragraphs x six candidates at
    the measured batched rate.
    """

    #: Eight, restored 2026-09-22. The 2026-09-20 cut to four (ranked by the
    #: free surrogate, one round) shipped AI-rated rewrites: only about one
    #: candidate in five is both faithful and GPTZero-human (.hip7b r4 bench,
    #: 26 of 120), so four draws rarely contain one. Eight per round, two
    #: rounds, GPTZero ranking passed 9 of 9 on 2026-09-11. Override per
    #: request.
    n_candidates: int = 8
    #: `faithful` (instruct checkpoint only), `freeform` (base checkpoint
    #: only) or `mixed` (alternate the two). `mixed` is the default under the
    #: `evade` objective because research/13 §2 puts base-model text at
    #: 96-99% human on GPTZero against 17-30% for the same model instruction
    #: tuned, and the base candidates were only ever losing here on the
    #: content gate, which `evade` relaxes.
    #: `freeform` (the base checkpoint, few-shot with the author's notes) is
    #: the default since the first live GPTZero measurements (research/24
    #: §6): it is the only style whose output GPTZero has read as human.
    #: `register` (Qwen3-4B-Instruct + LoRA) flips the four local detectors
    #: and none of GPTZero's verdicts; `faithful` moves neither.
    style: str = "freeform"
    aggressiveness: str = "strong"
    #: Soft budget for rounds *after* the first. Round 1 always rewrites every
    #: paragraph: a paragraph left unrewritten for budget is the one failure
    #: mode a user cannot tell apart from the product not working.
    time_budget_s: float = 30.0
    #: Later rounds re-run only the paragraphs still above `pass_threshold`.
    #: Two, restored 2026-09-22 with the eight candidates above (see
    #: `n_candidates`).
    rounds: int = 2
    #: A paragraph counts as passed only when its best candidate's scorer
    #: probability is under this. 0.15, not 0.5: the free surrogate's human
    #: calls are 92% right at 0.5 and about 96% right at 0.15 on held-out
    #: rewrites (research/24 §6.11), and a winner at 0.45 was exactly how the
    #: pipeline "changed" paragraphs GPTZero then called AI. When GPTZero
    #: itself is the scorer its own decision boundary, 0.5, applies (its
    #: label is the argmax of a three-way head, research/07 §2). Override
    #: with HUMANIZER_PASS_THRESHOLD.
    pass_threshold: float = field(default_factory=lambda: _default_pass_threshold())
    #: **The priority order.** `evade` (default since 2026-09-07): the
    #: detector score is the objective, the factual invariants (numbers,
    #: dates, quotations, citations, names) stay hard, and the three
    #: stylistic gates are widened to the values below. `faithful`: the
    #: original tight gates, for callers who want the old behaviour.
    objective: str = OBJECTIVE_EVADE
    #: How much a candidate's distance from the human-quality bands counts
    #: against it at selection, in units of AI probability. 0.0 ranks on the
    #: score alone; the "slowly improve the writing" knob is to raise this.
    quality_weight: float = 0.0
    #: Reject a candidate that keeps less than this share of the source's
    #: content words. See `content_overlap`. `None` means "the objective's
    #: default".
    min_content_overlap: Optional[float] = None
    #: |len(candidate)/len(source) - 1| may not exceed this.
    max_length_ratio_delta: Optional[float] = None
    #: Independent floor, stated separately because it is the failure that
    #: matters most: a candidate that silently drops half the paragraph.
    min_length_ratio: Optional[float] = None
    model: Optional[str] = None
    #: Names, dates, figures and sources the *author* vouches for, as free
    #: text. This is the only legitimate source of specifics a rewrite may
    #: add. The `register` adapter was trained to anchor every sentence in a
    #: concrete particular (research/00 §1a: the one register measured
    #: flipping every local detector), and measured on the bench it invents
    #: them: 6 of 6 candidates on 9 of 9 paragraphs failed `invariant:numbers`
    #: with figures the draft never contained (.kriukow/results_nonum.json;
    #: telling it not to had no effect). A fabricated statistic in an essay is
    #: worse than a detector verdict, so the invariants stay hard and the fix
    #: is to give the model true material: numbers, dates, quotations and
    #: citations that appear here are allowed into a candidate; anything else
    #: new is still rejected and reported as `unverified_specifics`.
    facts: str = ""
    #: A LoRA directory on the base checkpoint used for `freeform` candidates
    #: from round 3 onward, i.e. for paragraphs the plain base failed twice.
    #: The HIP-style adapter (research/24 §6.6) lifts GPTZero's per-candidate
    #: human rate from 45% to 63% but drifts more, so it is the second
    #: distribution to sample, not the first. Default from
    #: HUMANIZER_BASE_ADAPTER_RETRY; None or "" disables it.
    retry_adapter: Optional[str] = field(
        default_factory=lambda: os.environ.get("HUMANIZER_BASE_ADAPTER_RETRY") or None
    )
    #: The self-correcting stage (`repair.py`): after the last round, every
    #: paragraph still at or above `pass_threshold`, or kept unchanged, gets
    #: up to this many diagnose-and-retry attempts. 0 disables the stage.
    #: Default from HUMANIZER_REPAIR_ATTEMPTS. research/24 §6.14: the supply
    #: of faithful-and-human candidates is about one in seven and the
    #: failures cluster by cause, so a retry that changes what it asks for
    #: beats another draw from the same distribution.
    repair_attempts: int = field(
        default_factory=lambda: int(os.environ.get("HUMANIZER_REPAIR_ATTEMPTS") or 0)
    )
    #: Whether the free local detector scores every candidate so `select`
    #: can pick the lowest p(AI) among the faithful ones. On by default
    #: (HUMANIZER_SCORE_CANDIDATES=0 turns it off): measured 2026-09-20 it
    #: costs about 0.03 s a candidate once the surrogate is resident, and
    #: best-of-N against the GPTZero proxy is the one lever that moved the
    #: real verdict (research/24 §6). It is a *ranker only*: with `rounds=1`
    #: and `repair_attempts=0` no score can send a paragraph back for another
    #: pass or keep the original, which is what made the earlier build return
    #: drafts unchanged after minutes. Off, `select` ranks by the writing
    #: heuristics (`_heuristic_key`). A caller-supplied detector (the user's
    #: own GPTZero key) scores candidates regardless.
    #: Treat every input as AI-written: the analyze stage does not score the
    #: original, `before` is a fixed 100% AI verdict marked `assumed`, and
    #: every paragraph is rewritten. Owner's decision 2026-10-05: the product
    #: never spends a judge call on the input; a user who wants a real
    #: before/after verdict brings their own GPTZero key. Default on;
    #: HUMANIZER_ASSUME_AI=0 restores the measured `before`.
    assume_ai: bool = field(
        default_factory=lambda: (os.environ.get("HUMANIZER_ASSUME_AI") or "1").strip().lower()
        not in ("0", "false", "no", "off")
    )
    score_candidates: bool = field(
        default_factory=lambda: (os.environ.get("HUMANIZER_SCORE_CANDIDATES") or "1").strip().lower()
        not in ("0", "false", "no", "off")
    )
    #: Soft wall-clock budget for the whole repair stage, checked between
    #: attempts. Separate from `time_budget_s` because the owner asked for
    #: this stage to take the time it needs.
    repair_time_budget_s: float = 240.0
    #: Ask the instruct checkpoint, once per attempt, what the best failed
    #: rewrite did wrong and what one instruction would fix it, and feed the
    #: answer into the next attempt's notes. Off by default: a model call
    #: per attempt, and the measured diagnosis from the gates is usually
    #: enough. Default from HUMANIZER_REPAIR_CRITIC (1/true/yes).
    repair_critic: bool = field(
        default_factory=lambda: (os.environ.get("HUMANIZER_REPAIR_CRITIC") or "").strip().lower()
        in ("1", "true", "yes", "on")
    )

    def __post_init__(self) -> None:
        if self.objective not in GATE_PRESETS:
            raise ValueError(
                "objective must be one of %s" % ", ".join(sorted(GATE_PRESETS))
            )
        if self.style not in ("faithful", "freeform", "mixed", "register"):
            raise ValueError("style must be faithful, freeform, mixed or register")
        preset = GATE_PRESETS[self.objective]
        if self.min_content_overlap is None:
            self.min_content_overlap = preset["min_content_overlap"]
        if self.max_length_ratio_delta is None:
            self.max_length_ratio_delta = preset["max_length_ratio_delta"]
        if self.min_length_ratio is None:
            self.min_length_ratio = preset["min_length_ratio"]
        if self.repair_attempts < 0:
            raise ValueError("repair_attempts must be 0 or more")

    def styles(self) -> Tuple[str, ...]:
        return ("faithful", "freeform") if self.style == "mixed" else (self.style,)

    def model_for(self, style: str) -> str:
        """The checkpoint one style generates with.

        `model` overrides the instruct checkpoint only: a base checkpoint is
        a different object and there is no sensible single override for both.
        """
        if style == "freeform":
            return llm_mod.FREEFORM_MODEL
        if style == "register":
            return llm_mod.REGISTER_MODEL
        return self.model or llm_mod.DEFAULT_MODEL

    def resolved_model(self) -> str:
        return " + ".join(self.model_for(s) for s in self.styles())


# ------------------------------------------------------------ the detector


def _detector() -> Any:
    """The in-loop candidate scorer: `detectors.yardstick.proxy()`'s model.

    Local, free, a published checkpoint. It is *not* necessarily the yardstick:
    when `GPTZERO_API_KEY` is set the yardstick is GPTZero and this is the
    desklib stand-in that ranks fifty candidates without spending money on
    them. `yardstick.proxy()` returns the yardstick's own object when the two
    coincide, so nothing is loaded twice.
    """
    return yardstick_mod.proxy().detector


def _yardstick() -> Any:
    """The document-level verdict: `detectors.yardstick.resolve()`."""
    return yardstick_mod.resolve()


def _score(text: str, detector: Any) -> Optional[float]:
    """AI probability for one string, or None when the model cannot run."""
    if detector is None or not text or not text.strip():
        return None
    try:
        if hasattr(detector, "available") and not detector.available():
            return None
        value = float(detector.score(text).ai_probability)
    except Exception:  # noqa: BLE001 - a missing model must not fail a rewrite
        return None
    return None if value != value else value


def _score_and_label(text: str, detector: Any) -> Tuple[Optional[float], Optional[str]]:
    """Probability plus the detector's *own* label when it gives one.

    GPTZero returns a three-way verdict ({human, ai, mixed}) that is not a
    threshold on its probability (research/07 §2: the class is the argmax of
    a remapped document head). Reading the label off the result rather than
    re-deriving it from 0.5 is what makes `verdict_flipped` mean "GPTZero
    said human" when GPTZero is the yardstick. Detectors without a label fall
    back to the threshold.
    """
    if detector is None or not text or not text.strip():
        return None, None
    try:
        if hasattr(detector, "available") and not detector.available():
            return None, None
        result = detector.score(text)
    except Exception:  # noqa: BLE001
        return None, None
    try:
        probability: Optional[float] = float(result.ai_probability)
    except (TypeError, ValueError):
        probability = None
    if probability is not None and probability != probability:
        probability = None
    label = getattr(result, "label", None)
    if label not in ("human", "ai", "mixed"):
        label = _label(probability)
    return probability, label


def _label(probability: Optional[float]) -> Optional[str]:
    if probability is None:
        return None
    return "ai" if probability >= AI_THRESHOLD else "human"


