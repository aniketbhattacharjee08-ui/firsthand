def _plural(n: int, word: str) -> str:
    return "%d %s%s" % (n, word, "" if n == 1 else "s")


def _transfer(rows: Sequence[Tuple[Optional[float], Optional[float]]]) -> Dict[str, Any]:
    """Guide-versus-yardstick agreement over `(guide, yardstick)` pairs.

    research/08 §3.2 is the reason this is computed and reported rather than
    assumed: transfer between detectors is "real but wildly uneven", a 34-point
    spread inside a single paper, so "a mean improvement number is actively
    misleading". What is reported here is the raw disagreement -- mean signed
    gap, mean absolute gap, and how often the two land on opposite sides of
    0.5 -- because that, not a correlation coefficient over five points, is
    what tells a reader whether the search was optimising anything real.
    """
    pairs = [
        (float(g), float(y))
        for g, y in rows
        if g is not None and y is not None and math.isfinite(g) and math.isfinite(y)
    ]
    if not pairs:
        return {
            "n": 0,
            "mean_guide": None,
            "mean_yardstick": None,
            "mean_signed_gap": None,
            "mean_abs_gap": None,
            "verdict_disagreements": None,
            "note": "no paragraph was scored by both the guide and the yardstick",
        }
    n = len(pairs)
    mean_g = sum(g for g, _ in pairs) / n
    mean_y = sum(y for _, y in pairs) / n
    signed = sum(g - y for g, y in pairs) / n
    absolute = sum(abs(g - y) for g, y in pairs) / n
    disagree = sum(
        1 for g, y in pairs if (g >= AI_THRESHOLD) != (y >= AI_THRESHOLD)
    )
    return {
        "n": n,
        "mean_guide": round(mean_g, 6),
        "mean_yardstick": round(mean_y, 6),
        "mean_signed_gap": round(signed, 6),
        "mean_abs_gap": round(absolute, 6),
        "verdict_disagreements": disagree,
        "note": (
            "guide = %s (search heuristic); yardstick = %s (the reported "
            "number). A large gap means the search was optimising something "
            "the yardstick does not measure -- research/08 §3.2."
            % (GUIDE_MODEL, YARDSTICK_MODEL)
        ),
    }


# ------------------------------------------------------------- the search


def _search_paragraph(
    source: str,
    cfg: GuidedConfig,
    backend: llm_mod.Backend,
    guide: Any,
    emit: Callable[[float, str], ProgressEvent],
    deadline: Optional[float] = None,
) -> Iterator[ProgressEvent]:
    """Variant A. Beam search over sentences, ordered by the guide.

    A **generator**, not a function returning a tuple, and deliberately so: a
    paragraph's search is the 20-30 seconds a user spends staring at the
    progress bar, and a callback that buffers its events until the search
    finishes would render as a frozen `generate` stage followed by every
    event at once. `stream()` consumes it with `yield from`, which forwards
    each event the instant it is produced and delivers the search's
    `return` value as the expression result.

    Returns (via `StopIteration.value`, i.e. the `yield from` expression)
    `(finalists, steps, stats)`. `finalists` is the surviving beam,
    best first. `steps[i]` is every candidate considered at sentence `i`,
    including the ones the gate rejected, so the response can show the search
    rather than assert it.

    The loop, per source sentence:

    1. Every live hypothesis proposes `n_samples` continuations. All
       `beam_width x n_samples` prompts go to the backend in **one** call, so
       `MlxBackend` batches them (measured: 12 short prompts in ~2.0 s against
       ~7 s looped).
    2. Each completion is cleaned to a sentence and run through
       `sentence_gate`. Failures are recorded and dropped.
    3. Survivors are scored by the guide in `cfg.guide_context`.
    4. `select_beam` keeps the best `beam_width`.
    5. If *nothing* survives, every hypothesis extends with the source sentence
       verbatim. That is the honest failure: the paragraph keeps its meaning
       and the fallback is counted in `n_fallback_sentences`.

    The time budget is checked between sentences. A paragraph that runs out
    keeps the source's remaining sentences, which is why an overrun degrades
    into a partial rewrite rather than a truncated one.
    """
    sentences = split_sentences(source)
    if not sentences:
        sentences = [source.strip()]
    moves = sentence_moves(cfg.n_samples)

    beam: List[Hypothesis] = [Hypothesis()]
    steps: List[List[SentenceCandidate]] = []
    gen_seconds = 0.0
    gen_tokens = 0
    guide_calls = 0
    guide_seconds = 0.0
    batched = False
    budget_stop_at: Optional[int] = None

    for i, src_sentence in enumerate(sentences):
        if deadline is not None and time.perf_counter() > deadline and i > 0:
            budget_stop_at = i
            yield emit(
                i / len(sentences),
                "budget spent at sentence %d of %d; the rest is kept as written"
                % (i + 1, len(sentences)),
            )
            break

        following = sentences[i + 1] if i + 1 < len(sentences) else ""
        remaining = sentences[i + 1 :]
        requests: List[llm_mod.GenerationRequest] = []
        routing: List[Tuple[int, int]] = []
        for b, hyp in enumerate(beam):
            for j, (move, temperature) in enumerate(moves):
                requests.append(
                    llm_mod.GenerationRequest(
                        prompt=build_sentence_prompt(
                            hyp.text, src_sentence, move, following
                        ),
                        temperature=temperature,
                        max_tokens=sentence_max_tokens(src_sentence),
                        tag=(i, b, j),
                    )
                )
                routing.append((b, j))

        yield emit(
            i / len(sentences),
            "sentence %d of %d, %d beam x %d samples = %s"
            % (
                i + 1,
                len(sentences),
                len(beam),
                cfg.n_samples,
                _plural(len(requests), "continuation"),
            ),
        )
        batch = backend.generate(requests)
        gen_seconds += batch.seconds
        gen_tokens += batch.generation_tokens
        batched = batched or batch.batched

        step_records: List[SentenceCandidate] = []
        scored: List[Tuple[Optional[float], int, Hypothesis]] = []
        for n, ((b, j), raw) in enumerate(zip(routing, batch.texts)):
            move, temperature = moves[j]
            text = clean_sentence(raw)
            record = SentenceCandidate(
                step=i,
                parent=b,
                index=j,
                text=text,
                move=move,
                temperature=temperature,
            )
            record.gates = sentence_gate(
                src_sentence,
                text,
                min_overlap=cfg.min_sentence_overlap,
            )
            if record.passed:
                if guide is not None:
                    context = guide_context(
                        beam[b].text, text, remaining, cfg.guide_context
                    )
                    t0 = time.perf_counter()
                    record.guide_score = _score_with(guide, context)
                    guide_seconds += time.perf_counter() - t0
                    guide_calls += 1
                extended = beam[b].extend(text, record.guide_score, b, False)
                scored.append((record.guide_score, n, extended))
            step_records.append(record)

        if scored:
            beam = select_beam(scored, cfg.beam_width)
        else:
            # Nothing survived. Keep meaning, count the failure, carry on.
            # `guide_score=None` rather than the source sentence's own score:
            # a fallback is not a search result and must not be ranked as one.
            beam = [
                hyp.extend(src_sentence, None, b, True)
                for b, hyp in enumerate(beam)
            ]
            step_records.append(
                SentenceCandidate(
                    step=i,
                    parent=-1,
                    index=-1,
                    text=src_sentence,
                    move="(source sentence kept)",
                    fallback=True,
                )
            )
        steps.append(step_records)

    if budget_stop_at is not None:
        tail = sentences[budget_stop_at:]
        beam = [
            Hypothesis(
                sentences=hyp.sentences + tuple(tail),
                guide_score=hyp.guide_score,
                origin=hyp.origin + tuple(-1 for _ in tail),
                n_fallbacks=hyp.n_fallbacks + len(tail),
            )
            for hyp in beam
        ]

    stats = {
        "n_sentences": len(sentences),
        "generation_seconds": gen_seconds,
        "generation_tokens": gen_tokens,
        "guide_calls": guide_calls,
        "guide_seconds": guide_seconds,
        "batched": batched,
        "budget_truncated": budget_stop_at is not None,
    }
    return beam, steps, stats


# --------------------------------------------------- variant B: token level


def _eos_ids(tokenizer: Any) -> frozenset:
    """Every id that ends a turn for this tokenizer. Empty is survivable."""
    ids = set()
    for attr in ("eos_token_ids", "eos_token_id"):
        value = getattr(tokenizer, attr, None)
        if isinstance(value, int):
            ids.add(value)
        elif isinstance(value, (list, tuple, set, frozenset)):
            ids.update(int(v) for v in value)
    return frozenset(ids)


def token_guided_sentence(
    backend: Any,
    prompt: llm_mod.Prompt,
    temperature: float,
    max_tokens: int,
    cfg: GuidedConfig,
    guide: Any,
    prefix_text: str = "",
    remaining: Sequence[str] = (),
) -> Tuple[str, Dict[str, Any]]:
    """Variant B: decode one sentence with the guide inside the sampler.

    The published algorithm (research/05 §1.2) with one measured concession:
    the guide runs every `cfg.guidance_interval` tokens, not every token. At
    m=1, k=8 and 28 ms a call, a 60-token sentence costs 13.4 s of guide
    forward passes *before* any generation -- roughly half the entire budget
    for one sentence of one paragraph. m is a latency knob and the number is
    reported (`guided_steps`, `guide_calls`) rather than hidden.

    At a guided step: take the LM's top-`cfg.top_k` next tokens, decode each
    onto the text produced so far, score each with the guide in
    `cfg.guide_context`, reweight the logprobs with `reweight_logprobs` and
    sample from the reweighted top-k. At every other step the ordinary
    `mlx_lm` sampler runs untouched.

    Returns:
        `(text, stats)`. `stats` carries `guide_calls`, `guide_seconds`,
        `guided_steps`, `tokens` and `seconds`.

    Raises:
        RuntimeError: when MLX is not importable. Callers in this module catch
            it and fall back to `GuideMode.SEGMENT`, naming the reason.
    """
    try:
        import mlx.core as mx
        import numpy as np
        from mlx_lm.generate import generate_step
        from mlx_lm.sample_utils import make_sampler
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError(
            "token-level guidance needs mlx and numpy: %s. "
            "Use mode='segment', which needs neither." % exc
        ) from exc

    backend.load()
    model = getattr(backend, "_model", None)
    tokenizer = getattr(backend, "_tokenizer", None)
    if model is None or tokenizer is None:
        raise RuntimeError(
            "token-level guidance needs an MLX backend with a loaded model; "
            "%r exposes none. Use mode='segment'." % getattr(backend, "name", backend)
        )

    base_sampler = make_sampler(temp=float(temperature), top_p=0.99)
    produced: List[int] = []
    stats = {
        "guide_calls": 0,
        "guide_seconds": 0.0,
        "guided_steps": 0,
        "tokens": 0,
        "seconds": 0.0,
    }
    step = [0]
    remaining_text = " ".join(s.strip() for s in remaining if s and s.strip())

    def sampler(logprobs):
        n = step[0]
        step[0] = n + 1
        if (
            guide is None
            or cfg.guidance_strength == 0.0
            or n % cfg.guidance_interval != 0
        ):
            return base_sampler(logprobs)
        row = logprobs[0] if getattr(logprobs, "ndim", 1) > 1 else logprobs
        arr = np.asarray(row, dtype=np.float64)
        k = int(min(cfg.top_k, arr.shape[-1]))
        top = np.argpartition(-arr, k - 1)[:k]
        top = top[np.argsort(-arr[top])]
        scores: List[Optional[float]] = []
        for tid in top:
            piece = tokenizer.decode(produced + [int(tid)])
            context = guide_context(
                prefix_text, piece, [remaining_text], cfg.guide_context
            )
            t0 = time.perf_counter()
            scores.append(_score_with(guide, context))
            stats["guide_seconds"] += time.perf_counter() - t0
            stats["guide_calls"] += 1
        adjusted = reweight_logprobs(
            [float(arr[int(t)]) for t in top], scores, cfg.guidance_strength
        )
        stats["guided_steps"] += 1
        z = np.asarray(adjusted, dtype=np.float64) / max(1e-6, float(temperature))
        z = z - z.max()
        weights = np.exp(z)
        total = float(weights.sum())
        if not math.isfinite(total) or total <= 0.0:
            return base_sampler(logprobs)
        choice = int(np.random.choice(len(top), p=weights / total))
        return mx.array([int(top[choice])])

    eos = _eos_ids(tokenizer)
    started = time.perf_counter()
    prompt_tokens = mx.array(backend._encode(prompt))
    for token, _lp in generate_step(
        prompt_tokens, model, max_tokens=int(max_tokens), sampler=sampler
    ):
        tid = int(token.item() if hasattr(token, "item") else token)
        if tid in eos:
            break
        produced.append(tid)
    stats["tokens"] = len(produced)
    stats["seconds"] = time.perf_counter() - started
    return tokenizer.decode(produced), stats


class TokenGuidedBackend(llm_mod.Backend):
    """Adapts `token_guided_sentence` to the `llm.Backend` interface.

    Wrapping rather than branching inside `_search_paragraph` keeps variant B
    a drop-in for variant A's inner loop: the beam search, the gates, the
    fallbacks and the event stream are identical, and the only difference is
    where the guide is consulted. It also means variant B inherits variant A's
    beam for free, which the published depth-1 method does not have.

    It cannot batch -- the guide has to see one partial sequence at a time --
    so `batched` is False and each request is decoded in turn. That is the
    measured cost of the finer control, and it is why `GuideMode.TOKEN` is not
    the default.
    """

    name = "mlx-token-guided"

    def __init__(self, inner: Any, cfg: GuidedConfig, guide: Any):
        self.inner = inner
        self.cfg = cfg
        self.guide = guide
        self.model_name = getattr(inner, "model_name", "")
        self.stats = {"guide_calls": 0, "guide_seconds": 0.0, "guided_steps": 0}

    def available(self) -> bool:
        return self.inner.available()

    def unavailable_reason(self) -> Optional[str]:
        return self.inner.unavailable_reason()

    def load(self) -> None:
        self.inner.load()

    def generate(
        self, requests: Sequence[llm_mod.GenerationRequest]
    ) -> llm_mod.GenerationBatch:
        requests = list(requests)
        started = time.perf_counter()
        texts: List[str] = []
        tokens = 0
        for req in requests:
            text, stats = token_guided_sentence(
                self.inner,
                req.prompt,
                req.temperature,
                req.max_tokens,
                self.cfg,
                self.guide,
            )
            texts.append(text)
            tokens += int(stats["tokens"])
            for key in ("guide_calls", "guided_steps"):
                self.stats[key] += int(stats[key])
            self.stats["guide_seconds"] += float(stats["guide_seconds"])
        seconds = time.perf_counter() - started
        return llm_mod.GenerationBatch(
            texts=texts,
            seconds=seconds,
            generation_tokens=tokens,
            tokens_per_second=(tokens / seconds) if seconds > 0 else 0.0,
            batched=False,
            backend=self.name,
            model=self.model_name,
        )


