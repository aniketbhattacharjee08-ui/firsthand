def guided_available() -> bool:
    """Whether guided decoding can run at all right now."""
    return llm_mod.generation_available()


def guided_unavailable_reason() -> Optional[str]:
    """A user-facing sentence naming a fallback, or None when it can run.

    Two things can be missing and they have different fallbacks, so they are
    reported separately rather than collapsed into "unavailable": no MLX means
    no generation at all (fall back to the rule-based engine), while no torch
    means no *guide* -- which is a different, weaker failure handled inside
    `stream()`, not here, because a guideless run still produces text.
    """
    return llm_mod.generation_unavailable_reason()


def guide_unavailable_reason(model_name: str = GUIDE_MODEL) -> Optional[str]:
    """Why the in-loop guide cannot run, or None. Never raises."""
    try:
        det = _guide_detector(model_name)
        if det.available():
            return None
        return det.unavailable_reason() or "the guide detector is unavailable"
    except Exception as exc:  # noqa: BLE001 - availability must not raise
        return "%s: %s" % (type(exc).__name__, exc)


