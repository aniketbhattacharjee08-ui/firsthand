#: The system turn for a single-sentence rewrite. Deliberately shorter than
#: `llm._SYSTEM_FAITHFUL`: at sentence granularity the prompt is re-encoded
#: once per sentence per beam per sample, so a 300-token system message is
#: paid `beam x samples x sentences` times. The style exemplar is dropped for
#: the same reason and because the guide, not the prompt, is what steers here.
#: That is the whole thesis of the module -- if the prompt could do it,
#: `pipeline.py` would already have done it.
_SYSTEM = (
    "You rewrite one sentence at a time. You are a person writing, not an "
    "assistant: no preamble, no commentary, no quotation marks around the "
    "answer. Keep every number, name, date and quotation exactly as given. "
    "Output the rewritten sentence and nothing else."
)


def build_sentence_prompt(
    prefix: str,
    source_sentence: str,
    move: str = "",
    following: str = "",
) -> llm_mod.Prompt:
    """The prompt for one candidate rewrite of one sentence.

    Args:
        prefix: the rewrite so far. Shown as context so the continuation
            actually continues -- without it the model re-establishes the
            subject every sentence and the paragraph reads as a list.
        source_sentence: the sentence being rewritten. Placed last: this is
            the one thing the model must act on, and instruction-following
            degrades with distance from the end of the context.
        move: one of `SENTENCE_MOVES`, or empty.
        following: the next source sentence, shown as "what comes next" so the
            model does not write a closing sentence in the middle of a
            paragraph. Optional; empty on the last sentence, which is the one
            place a closing cadence is correct.

    Returns:
        A chat `llm.Prompt`, ready for any `llm.Backend`.

    Raises:
        ValueError: when `source_sentence` is empty.
    """
    if not source_sentence or not source_sentence.strip():
        raise ValueError("source_sentence must not be empty")

    parts: List[str] = []
    if prefix and prefix.strip():
        parts.append("Your rewrite so far:\n" + prefix.strip())
    else:
        parts.append("You are starting the paragraph.")
    if following and following.strip():
        parts.append(
            "After this sentence the draft goes on to say:\n" + following.strip()
        )
    if move:
        parts.append("How to write it: " + move)
    parts.append("Rewrite this sentence:\n" + source_sentence.strip())
    return llm_mod.Prompt(
        kind="chat",
        messages=(("system", _SYSTEM), ("user", "\n\n".join(parts))),
    )


_QUOTE_WRAP_RE = re.compile(r'^\s*["“‘\'](.*)["”’\']\s*$', re.DOTALL)
_LEAD_BULLET_RE = re.compile(r"^\s*(?:[-*•]|\d+[.)])\s+")


def clean_sentence(raw: str, max_sentences: int = 2) -> str:
    """One sentence (or two) out of a chat model's completion.

    `llm.clean_completion` already strips fences, `HUMAN:` labels, "Here is
    the revised paragraph:" preambles and trailing commentary; this adds the
    three failures specific to asking for a *single sentence*: the model
    wrapping the answer in quotation marks, prefixing it with a list bullet,
    and carrying on into the rest of the paragraph. `max_sentences` is 2
    rather than 1 because "Split it into two sentences of very different
    lengths" is one of `SENTENCE_MOVES` and truncating it to one would silently
    delete half the content the gate then blames the model for losing.
    """
    text = llm_mod.clean_completion(raw or "")
    text = text.strip()
    if not text:
        return ""
    # First non-empty line: a chat model that keeps going usually does it
    # after a newline, and a legitimate single sentence never contains one.
    for line in text.split("\n"):
        if line.strip():
            text = line.strip()
            break
    text = _LEAD_BULLET_RE.sub("", text)
    m = _QUOTE_WRAP_RE.match(text)
    if m and '"' not in m.group(1) and "”" not in m.group(1):
        text = m.group(1).strip()
    sentences = split_sentences(text)
    if len(sentences) > max_sentences:
        text = " ".join(sentences[:max_sentences])
    return " ".join(text.split()).strip()


def sentence_max_tokens(sentence: str, headroom: float = 1.9) -> int:
    """Generation cap for one sentence.

    `llm.estimate_max_tokens` floors at 96, which is right for a paragraph and
    three times too generous for a sentence: at beam 3 x 4 samples the floor is
    paid 12 times a step and `batch_generate` decodes until the *longest*
    stream in the batch finishes. Floored at 28 so a short sentence can still
    be split in two, capped at 200.
    """
    n_words = len(sentence.split())
    return int(max(28, min(200, n_words * 1.35 * headroom)))


# ----------------------------------------------------------------- the guide


def guide_context(
    prefix: str,
    candidate: str,
    remaining: Sequence[str] = (),
    mode: str = GuideContext.FULL,
) -> str:
    """The exact string handed to the guide detector for one candidate.

    Pure, so the choice of context is testable without a detector. See
    `GuideContext` for why `FULL` is the default.
    """
    if mode == GuideContext.SENTENCE:
        return candidate.strip()
    head = " ".join(p for p in (prefix.strip(), candidate.strip()) if p)
    if mode == GuideContext.PREFIX:
        return head
    tail = " ".join(s.strip() for s in remaining if s and s.strip())
    return " ".join(p for p in (head, tail) if p)


