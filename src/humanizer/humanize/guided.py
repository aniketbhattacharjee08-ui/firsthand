@dataclass
class SentenceCandidate:
    """One proposed rewrite of one source sentence, with everything measured.

    `guide_score` is the guide's, always, and is never copied into a field
    named `ai_probability`. There is no per-sentence yardstick score because
    running desklib per sentence per beam is 161 ms x beam x samples x
    sentences, which is the whole time budget for one paragraph.
    """

    step: int
    parent: int
    index: int
    text: str
    move: str = ""
    temperature: float = 0.0
    guide_score: Optional[float] = None
    gates: List[str] = field(default_factory=list)
    #: True when every candidate at this step failed and the source sentence
    #: was used verbatim instead.
    fallback: bool = False

    @property
    def passed(self) -> bool:
        return not self.gates

    def as_dict(self) -> Dict[str, Any]:
        return {
            "step": self.step,
            "parent": self.parent,
            "index": self.index,
            "text": self.text,
            "move": self.move,
            "temperature": self.temperature,
            "guide_score": None
            if self.guide_score is None
            else round(self.guide_score, 6),
            "gates": list(self.gates),
            "passed": self.passed,
            "fallback": self.fallback,
        }


@dataclass
class Hypothesis:
    """One live path through the beam: the sentences chosen so far.

    `guide_score` is the guide's score of the whole hypothesis in context at
    the step that produced it, which is what the beam is ordered by.
    `origin` traces which hypothesis of the previous step this extended, so
    the beam's bookkeeping is inspectable rather than a claim in a docstring.
    """

    sentences: Tuple[str, ...] = ()
    guide_score: Optional[float] = None
    origin: Tuple[int, ...] = ()
    n_fallbacks: int = 0

    @property
    def text(self) -> str:
        return " ".join(s.strip() for s in self.sentences if s.strip())

    def extend(
        self, sentence: str, guide_score: Optional[float], parent: int, fallback: bool
    ) -> "Hypothesis":
        return Hypothesis(
            sentences=self.sentences + (sentence,),
            guide_score=guide_score,
            origin=self.origin + (parent,),
            n_fallbacks=self.n_fallbacks + (1 if fallback else 0),
        )

    def as_dict(self) -> Dict[str, Any]:
        return {
            "text": self.text,
            "n_sentences": len(self.sentences),
            "guide_score": None
            if self.guide_score is None
            else round(self.guide_score, 6),
            "origin": list(self.origin),
            "n_fallbacks": self.n_fallbacks,
        }


def select_beam(
    scored: Sequence[Tuple[Optional[float], int, Hypothesis]],
    width: int,
) -> List[Hypothesis]:
    """Keep the `width` best hypotheses. Pure, so the bookkeeping is testable.

    `scored` is `(guide_score, tiebreak, hypothesis)`. Ordering rules, in
    order:

    1. Duplicate texts collapse to their first occurrence. Without this a
       sentence the model rewrites identically from three beams eats the whole
       beam, and the search silently becomes greedy.
    2. Unscored hypotheses (`guide_score is None`, i.e. no guide installed)
       sort after scored ones but are still kept, so a run without the guide
       degrades to "first `width` candidates" instead of returning nothing.
    3. Ties break on `tiebreak` ascending, which callers set to the candidate's
       generation index. Lower index means a cooler temperature and a more
       conservative structural move, so a tie resolves toward the safer edit.

    Raises:
        ValueError: when `width` is not positive.
    """
    if width <= 0:
        raise ValueError("width must be positive")
    seen: Dict[str, bool] = {}
    unique: List[Tuple[Optional[float], int, Hypothesis]] = []
    for score, tiebreak, hyp in scored:
        key = hyp.text.strip()
        if key in seen:
            continue
        seen[key] = True
        unique.append((score, tiebreak, hyp))
    unique.sort(
        key=lambda row: (
            row[0] is None,
            row[0] if row[0] is not None else 0.0,
            row[1],
        )
    )
    return [hyp for _score, _tb, hyp in unique[:width]]


# ------------------------------------------------------------------- gates


def sentence_gate(
    source_sentence: str,
    candidate: str,
    min_overlap: float = 0.45,
    max_length_ratio_delta: float = 0.75,
) -> List[str]:
    """Names of every per-sentence gate the candidate fails.

    The *same* invariant test the paragraph gate runs, applied one sentence
    earlier. `pipeline._invariant_failures` is called directly rather than
    copied: numbers, dates, quotations and citations are compared as exact
    multisets and every capitalised run in the source must survive verbatim.

    The two thresholds differ from the paragraph gate's on purpose and the
    difference is a loosening, not a hole:

    * `max_length_ratio_delta` is 0.75 against the paragraph's 0.25 because
      "Make it short and blunt" and "Let it run long" are two of eight
      `SENTENCE_MOVES` and both are exactly the sentence-length variance the
      rewrite is *for* (research/10: human sentence-length CV 0.42-0.60,
      AI 0.23). The paragraph-level ratio gate still runs afterwards on the
      assembled text, so total length cannot drift.
    * `min_overlap` is per sentence, where a single dropped noun is a much
      larger share of the content words than it is in a paragraph.

    Nothing here can let a paragraph through that
    `pipeline._gate_candidate` would reject: this runs *in addition to* it,
    never instead of it.
    """
    text = (candidate or "").strip()
    if not text:
        return ["empty"]
    n_source = len(words(source_sentence))
    n_candidate = len(words(text))
    if n_source == 0:
        return ["empty_source"]
    failures: List[str] = []
    ratio = n_candidate / n_source
    if abs(ratio - 1.0) > max_length_ratio_delta:
        failures.append("length_ratio")
    if content_overlap(source_sentence, text) < min_overlap:
        failures.append("content_drift")
    for name in pipeline_mod._invariant_failures(source_sentence, text):
        failures.append("invariant:" + name)
    return failures


# ------------------------------------------------------- token-level guidance


def reweight_logprobs(
    logprobs: Sequence[float],
    guide_scores: Sequence[Optional[float]],
    strength: float = 4.0,
) -> List[float]:
    """Bias a next-token distribution away from the guide's AI signal.

    The published method (research/05 §1.2) takes the argmax of the guide over
    the top-k candidate tokens, i.e. it discards the LM's own distribution
    entirely at every step. That is variant B at `strength=inf`, and it is
    measurably worse for text quality: it drives perplexity up and, with a weak
    guide, walks straight off the manifold. So this is a soft version --

        logprob'_i = logprob_i - strength * (guide_i - min(guide))

    -- which leaves the LM's ranking intact where the guide is indifferent and
    only overrides it where the guide separates the candidates. `strength=0`
    reproduces plain sampling exactly, which is the control this needs to have.

    Candidates the guide could not score keep their original logprob, so a
    guide failure degrades to ordinary sampling rather than to a uniform
    distribution over the top-k.

    Returns:
        A new list, same length and order as `logprobs`.

    Raises:
        ValueError: on a length mismatch, which would silently mis-attribute
            every score to the wrong token.
    """
    if len(logprobs) != len(guide_scores):
        raise ValueError(
            "logprobs and guide_scores must be the same length (%d vs %d)"
            % (len(logprobs), len(guide_scores))
        )
    finite = [g for g in guide_scores if g is not None and math.isfinite(g)]
    if not finite or strength == 0.0:
        return [float(lp) for lp in logprobs]
    floor = min(finite)
    out: List[float] = []
    for lp, g in zip(logprobs, guide_scores):
        if g is None or not math.isfinite(g):
            out.append(float(lp))
        else:
            out.append(float(lp) - float(strength) * (float(g) - floor))
    return out


# ------------------------------------------------------------------- config


@dataclass
class GuidedConfig:
    """Everything tunable about one guided run.

    The defaults are sized to the 30-second budget from measurements on an M4
    Pro: `batch_generate` of 12 short prompts on Qwen2.5-3B-Instruct-4bit runs
    ~2.0 s, the guide adds 12 x 28 ms = 0.34 s, so a 9-sentence paragraph is
    ~21 s and a second paragraph will overrun -- which `time_budget_s` catches
    between sentences, not mid-batch.

    The gate field names are `pipeline.PipelineConfig`'s, verbatim, so this
    object can be passed straight to `pipeline._gate_candidate`. That is the
    reuse, not a coincidence.
    """

    #: Live hypotheses carried between sentences. 1 is greedy; past 4 the
    #: batch stops fitting the budget. research/08 §1.5 (Stroebl et al.):
    #: with an imperfect verifier "optimal sampling attempts are often fewer
    #: than 10", and beam x samples is that count.
    beam_width: int = 3
    #: Continuations proposed per hypothesis per sentence.
    n_samples: int = 4
    mode: str = GuideMode.SEGMENT
    guide_context: str = GuideContext.FULL
    #: Guide every m tokens in `GuideMode.TOKEN`. At m=1 a 60-token sentence
    #: with k=8 is ~13 s of guide calls alone, so m=1 is not a usable setting
    #: and the default is not close to it.
    guidance_interval: int = 8
    #: Top-k next tokens scored at each guided step in `GuideMode.TOKEN`.
    top_k: int = 8
    #: See `reweight_logprobs`.
    guidance_strength: float = 4.0
    aggressiveness: str = "strong"
    time_budget_s: float = 30.0
    #: `pipeline.OBJECTIVE_EVADE` (default) or `OBJECTIVE_FAITHFUL`. Sets the
    #: three gate values below when they are left as `None`; see
    #: `pipeline.GATE_PRESETS`.
    objective: str = pipeline_mod.OBJECTIVE_EVADE
    #: Per-sentence content floor. See `sentence_gate`. `None` follows the
    #: objective: 0.30 under `evade`, 0.45 under `faithful`.
    min_sentence_overlap: Optional[float] = None
    #: --- names below are `PipelineConfig`'s and are read by its gate ---
    #: Author-vouched names, dates and figures; see `PipelineConfig.facts`.
    #: The guided prompts do not use it (a sentence-level continuation adds
    #: no particulars), but the paragraph gate honours it, so a run with the
    #: same facts as an LLM run judges candidates by the same rule.
    facts: str = ""
    min_content_overlap: Optional[float] = None
    max_length_ratio_delta: Optional[float] = None
    min_length_ratio: Optional[float] = None
    model: Optional[str] = None
    guide_model: str = GUIDE_MODEL

    def __post_init__(self) -> None:
        if self.objective not in pipeline_mod.GATE_PRESETS:
            raise ValueError(
                "objective must be one of %s"
                % ", ".join(sorted(pipeline_mod.GATE_PRESETS))
            )
        preset = pipeline_mod.GATE_PRESETS[self.objective]
        if self.min_content_overlap is None:
            self.min_content_overlap = preset["min_content_overlap"]
        if self.max_length_ratio_delta is None:
            self.max_length_ratio_delta = preset["max_length_ratio_delta"]
        if self.min_length_ratio is None:
            self.min_length_ratio = preset["min_length_ratio"]
        if self.min_sentence_overlap is None:
            self.min_sentence_overlap = preset["min_content_overlap"]

    def resolved_model(self) -> str:
        return self.model or llm_mod.DEFAULT_MODEL

    def validate(self) -> None:
        """Raise `ValueError` on a configuration that cannot run."""
        if self.beam_width <= 0:
            raise ValueError("beam_width must be positive")
        if self.n_samples <= 0:
            raise ValueError("n_samples must be positive")
        if self.mode not in GuideMode.ALL:
            raise ValueError("mode must be one of %s" % (GuideMode.ALL,))
        if self.guide_context not in GuideContext.ALL:
            raise ValueError("guide_context must be one of %s" % (GuideContext.ALL,))
        if self.guidance_interval <= 0:
            raise ValueError("guidance_interval must be positive")
        if self.top_k <= 0:
            raise ValueError("top_k must be positive")

    @property
    def fanout(self) -> int:
        """Generations per sentence step. The thing the budget is spent on."""
        return self.beam_width * self.n_samples


