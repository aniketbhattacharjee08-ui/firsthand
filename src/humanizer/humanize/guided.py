class GuideMode:
    """Which variant of detector-guided decoding to run.

    `SEGMENT` is variant A: a sentence-granularity beam search, tractable
    inside the 30-second budget. `TOKEN` is variant B, the published
    per-token method with the guide throttled to every m tokens.
    """

    SEGMENT = "segment"
    TOKEN = "token"

    ALL = (SEGMENT, TOKEN)


class GuideContext:
    """What the guide is shown when it scores a partial rewrite.

    `FULL` -- the rewritten prefix, the candidate, then the *source's* remaining
    sentences. The guide sees a constant-length, complete-looking document at
    every step, so the score difference between two candidates is attributable
    to the candidates rather than to how much text exists yet. Every detector
    here is document-trained and `detectors.local.MIN_RELIABLE_CHARS` is 250;
    scoring a 20-word prefix asks it a question it was never trained on.

    `PREFIX` -- the rewritten prefix plus the candidate, and nothing else. The
    literal reading of "score prefix + candidate". Kept because it is the
    honest baseline for whether `FULL` is doing anything.

    `SENTENCE` -- the candidate alone. Fastest, and the least reliable.
    """

    FULL = "full"
    PREFIX = "prefix"
    SENTENCE = "sentence"

    ALL = (FULL, PREFIX, SENTENCE)


#: Sentence-level structural moves. The paragraph-level `llm.CANDIDATE_SPECS`
#: do not transfer: "open on the concrete detail, not the abstraction" is an
#: instruction about a paragraph's shape and means nothing applied to one
#: sentence. These are the moves that change a *sentence's* shape, which is
#: what sentence-length CV and burstiness are made of (research/04, /10).
#: The temperature offset rises down the list so that the diversity comes from
#: the instruction first and the sampler second -- `pipeline.py` measured
#: temperature alone buying almost nothing.
SENTENCE_MOVES: Tuple[Tuple[str, float], ...] = (
    ("Keep it about the same length, but change the word order.", 0.7),
    ("Make it short and blunt. Under ten words if you can.", 0.9),
    ("Let it run long and a little uneven, with a clause that doubles back.", 1.0),
    ("Start with the concrete thing, not the abstraction.", 0.85),
    ("Split it into two sentences of very different lengths.", 1.05),
    ("Fold in a plain, ordinary word where a formal one sits now.", 0.95),
    ("Turn it around: put the end of the sentence at the front.", 1.1),
    ("Say it the way you would say it out loud to one person.", 1.15),
)


def sentence_moves(n: int) -> List[Tuple[str, float]]:
    """`n` (move, temperature) pairs, cycling with a rising temperature.

    Past `len(SENTENCE_MOVES)` the list repeats with +0.1 on the temperature
    per lap, capped at 1.4. Beyond about 1.4 Qwen2.5-3B-Instruct-4bit starts
    emitting non-words, which is a gate failure rather than diversity.
    """
    if n <= 0:
        raise ValueError("n must be positive")
    out: List[Tuple[str, float]] = []
    for i in range(n):
        move, temp = SENTENCE_MOVES[i % len(SENTENCE_MOVES)]
        lap = i // len(SENTENCE_MOVES)
        out.append((move, round(min(1.4, temp + 0.1 * lap), 3)))
    return out


