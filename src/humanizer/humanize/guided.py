"""Detector-guided decoding: generate under a detector's own signal.

Why this module exists, and what it is *not*
--------------------------------------------
`pipeline.py` measured three things into the ground and wrote them down:
rule-based rewriting flips 0 verdicts of 9, paragraph-level best-of-N over an
instruction-tuned 3B flips 0 of 9, and the controlling measurement is that
pushing *genuine human text* through the same model raises its detector score
from 0.18 to 0.66. The output distribution of the model is the thing the
detector fires on. Asking the model nicely does not move that distribution, so
best-of-N has nothing good to select from.

Detector-guided decoding (research/03 B.8, research/05 §1.2 -- Cheng,
Sadasivan et al., *Adversarial Paraphrasing*, NeurIPS 2025) attacks that
directly. Instead of describing the target register in a prompt, you put the
detector *inside* the decoding loop and steer away from it using its own
gradient-free signal. The published method scores the top-k next **tokens** at
every step with a guide detector and emits the lowest-scoring one -- "a
targeted, detector-guided beam search at depth one" -- and reports an 87.88%
mean reduction in TPR@1%FPR across eight detectors.

Two variants are implemented here.

**A. Segment-guided search (`GuideMode.SEGMENT`, the default).** Generation
runs sentence by sentence. At each step every live hypothesis proposes
`n_samples` continuations of the *next source sentence*; each is scored with
the guide in context; the best `beam_width` survive. This is best-of-N at
sentence granularity with a beam, which is a far finer control surface than
the paragraph-level best-of-N that already failed: a 9-sentence paragraph with
beam 3 and 4 samples gives 3^9 reachable sequences explored through 108 guide
calls, against 6 whole-paragraph draws.

**B. Token-level guidance (`GuideMode.TOKEN`).** The published method, with one
concession to latency: the guide runs every `guidance_interval` tokens rather
than every token, because a guide call is ~28 ms and a 60-token sentence at
m=1 with k=8 is 13 seconds *for one sentence*. At the guided steps the LM's
top-k logprobs are reweighted by the guide's delta (`reweight_logprobs`) and a
token is sampled from the reweighted distribution. Off by default; see
`GuidedConfig.mode` and the measured numbers in the module test suite.

The guide is not the yardstick, and the distinction is load-bearing
-------------------------------------------------------------------
The in-loop guide is `MayZhou/e5-small-lora-ai-generated-detector` -- 33M
parameters, measured here at 28.5 ms a document against desklib's 161 ms.
research/05 §4 names exactly this checkpoint for exactly this job. It is also,
by this repo's own bench (`detectors.local.PUBLISHED_DETECTORS["fast"]`), a
detector that calls 8 of 14 genuine human PMC paragraphs AI. It is a search
heuristic. It is not evidence.

So **every reported probability in this module's output comes from the
yardstick**, `desklib/ai-text-detector-v1.01`, the same detector `pipeline.py`
reports and the same one `/api/detect` defaults to. The guide's own score is
carried alongside, in a separate `guide` block, labelled, and never substituted
for the yardstick. `summary["verdict_flipped"]`, `after["ai_probability"]` and
`summary["risk_delta"]` are desklib numbers and nothing else. research/08 §2.2
is blunt about why: a surrogate's posterior "carries no information about a
different classifier trained on different data", and best-of-N takes the
*argmax* of the surrogate, which is precisely where surrogate and target
disagree most. `summary["guide_transfer"]` reports that gap explicitly rather
than hoping about it.

What this actually achieves, measured
-------------------------------------
Measured on an M4 Pro against `desklib/ai-text-detector-v1.01`, on the same
corpus `.llmbench/bench.py` used for the LLM pipeline -- 9 AI paragraphs (3
hand-written in the stereotypical register, 6 generated by
Qwen2.5-3B-Instruct) and 5 human PMC paragraphs -- at beam 3 x 4 samples.

===========================  ==========  ==========  ============  =========
metric                       rule-based  LLM best-6  **guided**    unguided
                                                                   beam
===========================  ==========  ==========  ============  =========
verdict flips (ai -> human)  **0 of 9**  **0 of 9**  **0 of 9**    0 of 9
mean p(AI) change            -0.000013   -0.000130   -0.014619     -0.000649
mean logit(p) change         -0.36       -1.67       **-2.92**     -1.82
best single logit change     --          -2.90       **-8.57**     -4.79
mean sentence-length CV      0.219       0.304       **0.368**     0.202
in the 0.42-0.60 CV band     0 of 9      0 of 9      **4 of 9**    0 of 9
mean AI vocabulary per 1k    14.9        13.7        11.8          --
mean content overlap         --          --          0.79          0.85
mean wall clock              < 0.1 s     12.4 s      43 s          --
===========================  ==========  ==========  ============  =========

**It does not flip the verdict either.** That is the third independent
negative result on this corpus and it is the headline; the probability drop is
0.015 and the honest reading of it is "nothing". Say that first.

Three things it *does* do, and they are real:

1. It moves the detector further than anything else tried here. In
   probability the numbers are meaningless because desklib is saturated -- it
   returns 0.99998 for every source paragraph -- so the movement is quoted in
   logits, where a flip needs **-11.03** and this gets **-2.92** on average
   and **-8.57** on its best sample (`ai-gen-sleep`, 1.0000 -> 0.8776). The
   LLM pipeline's much-quoted "0.0001" was -1.67 logits. Guided decoding is
   1.75x that and is the first method here to land a sample within 2.5 logits
   of the threshold.
2. It is the first method here to reach the human sentence-length CV band:
   0.232 -> 0.368 mean, 4 of 9 samples inside 0.42-0.60, against 0 of 9 for
   both earlier engines. That comes from the guide, not from the beam -- see
   the ablation below.
3. It does not damage human text. Over the 5 PMC paragraphs the largest
   upward movement was **0.0000** and the mean change was -0.0278 (one
   paragraph improved from 0.1765 to 0.0375); 4 of 5 were returned untouched
   because the paragraph gate rejected every finalist.

Two ablations, and what they say about why it fails
----------------------------------------------------
**The guide is doing work.** Running the identical beam search, identical
gates and identical sampling with no guide at all (`guide=False`) gives -1.82
logits and moves the sentence-length CV the *wrong* way, 0.232 -> 0.202, with
0 of 9 in the band. So roughly a third of the movement and all of the
stylometric gain is attributable to the detector signal rather than to
resampling.

**But the weak proxy is not the reason it fails.** The obvious suspect is the
33M guide: research/08 §3.2 measures detector-to-detector transfer as "real
but wildly uneven", and this run reproduces exactly that shape -- the guide's
own score falls 0.94 -> 0.82 while desklib falls 0.99998 -> 0.985, a 6.7x
disagreement in probability, with a Pearson correlation of 0.87 between the
two deltas. Directionally honest, wildly attenuated in magnitude.

So the experiment was run again with **desklib itself as the in-loop guide** --
no proxy, no transfer gap, the search optimising the exact classifier that
judges it, at 161 ms a call instead of 28 ms. Result: **0 of 9 flips**,
-3.98 logits, mean p(AI) change -0.0042. Better in logits than the e5 guide,
worse in probability, and no closer to a verdict.

That is the finding. **The binding constraint is the generator, not the
verifier.** Search cannot select text that the model never proposes, and
across 9 paragraphs x 7 sentences x 12 candidates -- roughly 750 sentence
rewrites scored against desklib directly -- the best assembled paragraph the
model produced still scored 0.977. It is the same wall `pipeline.py` hit from
the other side: passing genuine human text through this checkpoint *raises*
its score from 0.18 to 0.66, so the model's output distribution is inside the
detector's AI region no matter which path through it you pick. Guided decoding
searches that region more finely than best-of-N does, and gets meaningfully
further, and the region does not reach 0.5.

Variant B, measured
-------------------
Token-level guidance was run at a *matched* budget against variant A -- beam 1
x 2 samples, m=8, k=8, over the three hand-written AI paragraphs -- because
comparing it against variant A's default beam 3 x 4 would compare search
budgets, not methods. At 12.4 s a paragraph against variant A's 12.3 s:

=========================  ==========  ==========
metric                     A segment   B token
=========================  ==========  ==========
verdict flips              0 of 3      0 of 3
mean logit(p) change       -2.07       **-3.00**
best single logit change   -3.71       **-6.07**
guide calls per paragraph  9           329
guide seconds              0.2         2.3
decode rate                26.9 tok/s  21.8 tok/s
=========================  ==========  ==========

So the finer control surface is worth about 45% more movement per second, and
`m=8` is why: 329 guide calls cost 2.3 s at 28 ms each, which is affordable,
while `m=1` on the same paragraphs would be roughly 2,600 calls and 74 s. It
still flips nothing, on three samples, and three samples is not a result --
it is reported because a measured number beats an unmeasured claim, not
because it settles anything. `GuideMode.SEGMENT` stays the default because it
batches and variant B cannot.

The Gao/Stroebl reading in research/08 §2.1 applies but is not the whole
story: this is not an over-optimisation turnover, since gold performance kept
improving with the better guide. It is the Stroebl ceiling -- an imperfect
*generator* bounds what any amount of verification can reach.

Gates are `pipeline.py`'s, imported not reimplemented
-----------------------------------------------------
`pipeline._invariant_failures` (numbers, quotations, citations and dates as
exact multisets; the entity test directional) and `pipeline._gate_candidate`
(length ratio, floor, content overlap, invariants, unchanged) run on the
assembled paragraph exactly as they run on an LLM candidate, and
`pipeline._scrub` runs the same deterministic transform passes. A second copy
of a meaning gate is how two code paths start disagreeing about what a safe
edit is. There is one addition, not a relaxation: `sentence_gate` applies the
same invariant check *per sentence* during the search, so a candidate that
drops a number is rejected at the step that produced it instead of poisoning
a whole beam. A sentence whose candidates all fail falls back to the source
sentence verbatim, which is reported, never hidden.

Progress events
---------------
`stream()` yields `pipeline.ProgressEvent` -- the same class, not a lookalike
-- over the same stage names in the same order::

    analyze plan generate scrub score verify select finalize

`STAGES` is re-exported so `/api/humanize/guided/health` can publish it and the
frontend's checklist works unchanged. Inside `generate` the `detail` string
reports the beam step ("paragraph 1 of 2, sentence 4 of 9, beam 3 x 4
samples"); no new stage was needed for the search because the search *is* the
generate stage. `score` is where the yardstick runs, and its detail says so.
"""

