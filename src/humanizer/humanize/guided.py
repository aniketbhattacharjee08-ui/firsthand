def stream(
    text: str,
    config: Optional[GuidedConfig] = None,
    backend: Optional[llm_mod.Backend] = None,
    detector: Any = None,
    guide: Any = None,
) -> Iterator[ProgressEvent]:
    """Run detector-guided decoding, yielding a `ProgressEvent` per step.

    Args:
        text: the document. Normalised on entry.
        config: see `GuidedConfig`. `None` uses the defaults.
        backend: an `llm.Backend`. `None` builds `llm.default_backend`. Tests
            pass `llm.EchoBackend`.
        detector: **the yardstick.** Anything with
            `.score(text).ai_probability`. `None` uses the process-wide
            desklib `ModernDetector` -- the same instance `pipeline.py` uses.
            Pass `False` to score nothing.
        guide: **the in-loop search heuristic**, a separate object from
            `detector` and never a substitute for it. `None` builds the
            e5-small guide. Pass `False` to run the beam search unguided,
            which is the control this module needs to have: an unguided run
            with the same beam and the same gates isolates how much of any
            movement came from the guide rather than from resampling.

    Yields:
        `ProgressEvent`s in `STAGES` order. The final one is `finalize/done`
        and carries `result`.

    Raises:
        ValueError: on empty input or an invalid config.
        RuntimeError: when the generation backend cannot load. The message
            names the fallback.
    """
    if not text or not text.strip():
        raise ValueError("text must not be empty")
    cfg = config or GuidedConfig()
    cfg.validate()

    clock = pipeline_mod._Clock()
    stage_timings: List[Dict[str, Any]] = []
    stage_started: Dict[str, float] = {}

    def event(
        stage: str,
        status: str,
        progress: float,
        detail: str,
        result: Optional[Dict[str, Any]] = None,
    ) -> ProgressEvent:
        now = clock()
        if status == "start":
            stage_started[stage] = now
        if status in ("done", "skip"):
            started = stage_started.pop(stage, now)
            stage_timings.append(
                {
                    "stage": stage,
                    "status": status,
                    "seconds": round(now - started, 3),
                    "detail": detail,
                    "round": 1,
                }
            )
        return ProgressEvent(stage, status, progress, detail, now, 1, result)

    if detector is False:
        yardstick = None
        finalist_scorer = None
    elif detector is None:
        yardstick = _yardstick()
        finalist_scorer = _finalist_scorer()
    else:
        yardstick = detector
        finalist_scorer = detector
    yardstick_name = (
        yardstick.model
        if isinstance(yardstick, yardstick_mod.Yardstick)
        else (pipeline_mod._scorer_name(yardstick) if yardstick is not None else "nothing")
    )
    guide_reason: Optional[str] = None
    if guide is False:
        guide_obj = None
        guide_reason = "guide disabled by the caller; the beam search is unguided"
    elif guide is None:
        guide_obj = _guide_detector(cfg.guide_model)
        guide_reason = guide_unavailable_reason(cfg.guide_model)
        if guide_reason is not None:
            guide_obj = None
    else:
        guide_obj = guide

    if backend is None:
        backend = llm_mod.default_backend("faithful", cfg.model)

    # -- analyze ----------------------------------------------------------
    yield event("analyze", "start", 0.0, "reading the document")
    original = normalize(text)
    segments = _paragraph_segments(original)
    doc = Document.parse(original)
    yield event(
        "analyze",
        "progress",
        0.4,
        "%s, %s, %s"
        % (
            _plural(len(segments), "paragraph"),
            _plural(doc.n_sentences, "sentence"),
            _plural(doc.n_words, "word"),
        ),
    )
    before = _measure(original, yardstick)
    p_before = before["ai_probability"]
    guide_before = _score_with(guide_obj, original)
    yield event(
        "analyze",
        "done",
        1.0,
        "scored the original with %s: %s"
        % (
            yardstick_name,
            "detector unavailable"
            if p_before is None
            else "p(AI) %.3f, labelled %s" % (p_before, before["label"]),
        ),
    )

    # -- plan -------------------------------------------------------------
    yield event("plan", "start", 0.0, "sizing the search")
    n_sentences = doc.n_sentences or len(segments)
    if cfg.mode == GuideMode.TOKEN and guide_obj is not None:
        try:
            backend = TokenGuidedBackend(backend, cfg, guide_obj)
        except Exception as exc:  # noqa: BLE001 - fall back, never fail
            guide_reason = (
                "token-level guidance unavailable (%s); ran segment-guided "
                "search instead" % exc
            )
            cfg.mode = GuideMode.SEGMENT
    elif cfg.mode == GuideMode.TOKEN:
        guide_reason = (guide_reason or "") + (
            " token-level guidance needs a guide; ran segment-guided search"
        )
        cfg.mode = GuideMode.SEGMENT
    yield event(
        "plan",
        "done",
        1.0,
        "%s mode, beam %d x %d samples = %s per sentence, %s, guide %s, "
        "budget %.0fs"
        % (
            cfg.mode,
            cfg.beam_width,
            cfg.n_samples,
            _plural(cfg.fanout, "continuation"),
            _plural(n_sentences, "sentence"),
            "unavailable (%s)" % guide_reason if guide_obj is None else GUIDE_ENGINE,
            cfg.time_budget_s,
        ),
    )

    outcomes = [
        GuidedParagraph(index=i, original=s, chosen=s) for i, s in enumerate(segments)
    ]
    for outcome in outcomes:
        outcome.ai_probability_before = _score_with(yardstick, outcome.original)
        outcome.guide_probability_before = _score_with(guide_obj, outcome.original)

    # -- generate ---------------------------------------------------------
    yield event("generate", "start", 0.0, "loading %s" % cfg.resolved_model())
    backend.load()

    totals = {
        "generation_seconds": 0.0,
        "generation_tokens": 0,
        "guide_calls": 0,
        "guide_seconds": 0.0,
    }
    batched = False
    deadline = clock.t0 + cfg.time_budget_s
    for n, outcome in enumerate(outcomes):
        if clock() > cfg.time_budget_s and n > 0:
            yield event(
                "generate",
                "progress",
                n / max(1, len(outcomes)),
                "budget spent after paragraph %d of %d; %d left as written"
                % (n, len(outcomes), len(outcomes) - n),
            )
            break

        def emit(fraction: float, detail: str, _n: int = n) -> ProgressEvent:
            return event(
                "generate",
                "progress",
                (_n + fraction) / max(1, len(outcomes)),
                "paragraph %d of %d, %s" % (_n + 1, len(outcomes), detail),
            )

        # `yield from` forwards each search event live and binds the search's
        # return value. A callback would buffer the whole paragraph.
        finalists, steps, stats = yield from _search_paragraph(
            outcome.original, cfg, backend, guide_obj, emit, deadline
        )
        outcome.steps = steps
        outcome.n_sentences = stats["n_sentences"]
        outcome.finalists = [h.as_dict() for h in finalists]
        outcome.n_fallback_sentences = (
            min(h.n_fallbacks for h in finalists) if finalists else 0
        )
        outcome.finalist_objects = finalists
        totals["generation_seconds"] += stats["generation_seconds"]
        totals["generation_tokens"] += stats["generation_tokens"]
        totals["guide_calls"] += stats["guide_calls"]
        totals["guide_seconds"] += stats["guide_seconds"]
        batched = batched or stats["batched"]
        yield event(
            "generate",
            "progress",
            (n + 1) / max(1, len(outcomes)),
            "paragraph %d of %d: %s survived, %d guide calls in %.1fs"
            % (
                n + 1,
                len(outcomes),
                _plural(len(finalists), "hypothesis" if len(finalists) == 1 else "hypothes"),
                stats["guide_calls"],
                stats["guide_seconds"],
            ),
        )
    if isinstance(backend, TokenGuidedBackend):
        totals["guide_calls"] += backend.stats["guide_calls"]
        totals["guide_seconds"] += backend.stats["guide_seconds"]
    yield event(
        "generate",
        "done",
        1.0,
        "%.1fs of generation, %d guide calls costing %.1fs, %s"
        % (
            totals["generation_seconds"],
            totals["guide_calls"],
            totals["guide_seconds"],
            "batched decode" if batched else "one at a time",
        ),
    )

    # -- scrub ------------------------------------------------------------
    # `pipeline._scrub`, unchanged. After the model, never before: the
    # instruct checkpoint reintroduces the vocabulary this pass removes.
    yield event("scrub", "start", 0.0, "applying deterministic transforms")
    scrubbed: Dict[int, List[str]] = {}
    n_edits = 0
    for n, outcome in enumerate(outcomes):
        finalists = outcome.finalist_objects
        texts: List[str] = []
        for hyp in finalists:
            cleaned, edits = pipeline_mod._scrub(hyp.text, cfg.aggressiveness)
            texts.append(cleaned)
            n_edits += len(edits)
        scrubbed[outcome.index] = texts
        yield event(
            "scrub",
            "progress",
            (n + 1) / max(1, len(outcomes)),
            "paragraph %d of %d, %s"
            % (n + 1, len(outcomes), _plural(len(texts), "finalist")),
        )
    yield event(
        "scrub",
        "done",
        1.0,
        "%s across %s"
        % (
            _plural(n_edits, "deterministic edit"),
            _plural(sum(len(v) for v in scrubbed.values()), "finalist"),
        ),
    )

    # -- score ------------------------------------------------------------
    # THE YARDSTICK RUNS HERE, AND ONLY HERE. Everything above this line was
    # scored by the guide, which is a search heuristic and is not reported as
    # a probability of anything.
    finalist_scores: Dict[int, List[Optional[float]]] = {}
    if yardstick is None:
        yield event(
            "score",
            "skip",
            1.0,
            "no yardstick detector available; finalists cannot be ranked by "
            "the reported score",
        )
        finalist_scores = {i: [None] * len(v) for i, v in scrubbed.items()}
    else:
        yield event(
            "score",
            "start",
            0.0,
            "scoring finalists with %s" % pipeline_mod._scorer_name(finalist_scorer),
        )
        for n, outcome in enumerate(outcomes):
            row = [_score_with(finalist_scorer, t) for t in scrubbed[outcome.index]]
            finalist_scores[outcome.index] = row
            yield event(
                "score",
                "progress",
                (n + 1) / max(1, len(outcomes)),
                "paragraph %d of %d: %s"
                % (
                    n + 1,
                    len(outcomes),
                    ", ".join(
                        "unscored" if p is None else "p(AI) %.3f" % p for p in row
                    )
                    or "no finalist",
                ),
            )
        yield event(
            "score",
            "done",
            1.0,
            "scored %d finalists with the yardstick"
            % sum(len(v) for v in finalist_scores.values()),
        )

    # -- verify -----------------------------------------------------------
    # `pipeline._gate_candidate`, imported not reimplemented.
    yield event("verify", "start", 0.0, "checking hard gates")
    survivors: Dict[int, List[Tuple[Optional[float], int, str]]] = {}
    all_gates: Dict[str, int] = {}
    for n, outcome in enumerate(outcomes):
        rows: List[Tuple[Optional[float], int, str]] = []
        failures: List[str] = []
        for j, candidate in enumerate(scrubbed[outcome.index]):
            gates = pipeline_mod._gate_candidate(outcome.original, candidate, cfg)
            for g in gates:
                all_gates[g] = all_gates.get(g, 0) + 1
            if gates:
                failures.extend(gates)
            else:
                rows.append((finalist_scores[outcome.index][j], j, candidate))
        survivors[outcome.index] = rows
        outcome.gates = sorted(set(failures))
        yield event(
            "verify",
            "progress",
            (n + 1) / max(1, len(outcomes)),
            "paragraph %d of %d: %d of %s passed every gate%s"
            % (
                n + 1,
                len(outcomes),
                len(rows),
                _plural(len(scrubbed[outcome.index]), "finalist"),
                "" if rows else " (%s)" % ", ".join(sorted(set(failures))),
            ),
        )
    yield event(
        "verify",
        "done",
        1.0,
        "%d of %s passed every gate"
        % (
            sum(len(v) for v in survivors.values()),
            _plural(sum(len(v) for v in scrubbed.values()), "finalist"),
        ),
    )

    # -- select -----------------------------------------------------------
    yield event("select", "start", 0.0, "ranking survivors by the yardstick")
    for n, outcome in enumerate(outcomes):
        rows = survivors[outcome.index]
        if not rows:
            outcome.fallback_reason = (
                "no finalist passed the gates (%s); kept the original"
                % (", ".join(outcome.gates) or "nothing was generated")
            )
            outcome.ai_probability_after = outcome.ai_probability_before
            outcome.guide_probability_after = outcome.guide_probability_before
            yield event(
                "select",
                "progress",
                (n + 1) / max(1, len(outcomes)),
                "paragraph %d of %d: every finalist rejected, keeping the original"
                % (n + 1, len(outcomes)),
            )
            continue
        scored_rows = [r for r in rows if r[0] is not None]
        if scored_rows:
            best = min(scored_rows, key=lambda r: (r[0], r[1]))
        else:
            best = min(rows, key=lambda r: r[1])
        outcome.chosen = best[2]
        outcome.ai_probability_after = best[0]
        outcome.guide_probability_after = _score_with(guide_obj, best[2])
        outcome.quality = _quality(outcome.original, best[2])
        yield event(
            "select",
            "progress",
            (n + 1) / max(1, len(outcomes)),
            "paragraph %d of %d: finalist %d wins (%s), %d survived"
            % (
                n + 1,
                len(outcomes),
                best[1] + 1,
                "unscored"
                if best[0] is None
                else "p(AI) %.3f by the yardstick" % best[0],
                len(rows),
            ),
        )
    yield event(
        "select",
        "done",
        1.0,
        "%d of %s rewritten"
        % (
            sum(1 for o in outcomes if o.changed),
            _plural(len(outcomes), "paragraph"),
        ),
    )

    # -- repair -----------------------------------------------------------
    # The stage exists in `pipeline.STAGES` so both pipelines feed one
    # checklist; the guided search's per-sentence fallback is its repair.
    yield event("repair", "skip", 1.0, "no repair stage in the guided search")

    # -- finalize ---------------------------------------------------------
    yield event("finalize", "start", 0.0, "reassembling and re-measuring")
    humanized = "\n\n".join(o.chosen.strip() for o in outcomes if o.chosen.strip())
    after = _measure(humanized, yardstick)
    p_after = after["ai_probability"]
    guide_after = _score_with(guide_obj, humanized)

    transfer = _transfer(
        [(o.guide_probability_after, o.ai_probability_after) for o in outcomes]
        + [(guide_after, p_after)]
    )
    summary = {
        "engine": "guided",
        "mode": cfg.mode,
        "model": cfg.resolved_model(),
        "backend": getattr(backend, "name", ""),
        "guide_model": cfg.guide_model if guide_obj is not None else None,
        "guide_engine": GUIDE_ENGINE if guide_obj is not None else None,
        "guide_available": guide_obj is not None,
        "guide_unavailable_reason": guide_reason,
        "yardstick_model": yardstick_name,
        "yardstick": yardstick.describe()
        if isinstance(yardstick, yardstick_mod.Yardstick)
        else None,
        "candidate_scorer": pipeline_mod._scorer_name(finalist_scorer)
        if finalist_scorer is not None
        else None,
        "objective": cfg.objective,
        "beam_width": cfg.beam_width,
        "n_samples": cfg.n_samples,
        "guide_context": cfg.guide_context,
        "n_edits": 0,
        "n_paragraphs": len(outcomes),
        "n_sentences": sum(o.n_sentences for o in outcomes),
        "n_fallback_sentences": sum(o.n_fallback_sentences for o in outcomes),
        "paragraphs_rewritten": sum(1 for o in outcomes if o.changed),
        "paragraphs_unchanged": sum(1 for o in outcomes if not o.changed),
        "gate_rejections": dict(sorted(all_gates.items())),
        "quality_flags": _flag_counts(outcomes),
        "content_overlap": round(content_overlap(original, humanized), 4),
        # Every number below is the yardstick's. See the module docstring.
        "risk_delta": None
        if (p_before is None or p_after is None)
        else round(p_after - p_before, 6),
        "label_before": before.get("label"),
        "label_after": after.get("label"),
        "verdict_flipped": bool(
            before.get("label") == "ai" and after.get("label") == "human"
        ),
        "guide_transfer": transfer,
        "seconds": round(clock(), 3),
        "generation_seconds": round(totals["generation_seconds"], 3),
        "generation_tokens": totals["generation_tokens"],
        "guide_calls": totals["guide_calls"],
        "guide_seconds": round(totals["guide_seconds"], 3),
        "tokens_per_second": round(
            totals["generation_tokens"] / totals["generation_seconds"], 1
        )
        if totals["generation_seconds"] > 0.05
        else None,
        "batched": batched,
    }
    guide_block = {
        "model": cfg.guide_model if guide_obj is not None else None,
        "engine": GUIDE_ENGINE if guide_obj is not None else None,
        "available": guide_obj is not None,
        "reason": guide_reason,
        "probability_before": guide_before,
        "probability_after": guide_after,
        "delta": None
        if (guide_before is None or guide_after is None)
        else round(guide_after - guide_before, 6),
        "calls": totals["guide_calls"],
        "seconds": round(totals["guide_seconds"], 3),
        "note": (
            "This is the in-loop search heuristic, not a verdict. It called 8 "
            "of 14 genuine human PMC paragraphs AI on this repo's own bench. "
            "The reported probability is `after.ai_probability`, from %s."
            % YARDSTICK_MODEL
        ),
    }
    result = GuidedResult(
        original=original,
        humanized=humanized,
        model=cfg.resolved_model(),
        backend=getattr(backend, "name", ""),
        before=before,
        after=after,
        guide=guide_block,
        summary=summary,
        paragraphs=outcomes,
        stages=stage_timings,
    )
    detail = "%s in %.1fs" % (
        "verdict flipped ai -> human"
        if summary["verdict_flipped"]
        else "verdict unchanged (%s)" % (after.get("label") or "unscored"),
        summary["seconds"],
    )
    now = clock()
    stage_timings.append(
        {
            "stage": "finalize",
            "status": "done",
            "seconds": round(now - stage_started.pop("finalize", now), 3),
            "detail": detail,
            "round": 1,
        }
    )
    yield ProgressEvent(
        stage="finalize",
        status="done",
        progress=1.0,
        detail=detail,
        elapsed=now,
        round=1,
        result=result.as_dict(),
        result_object=result,
    )


def _flag_counts(outcomes: Sequence[GuidedParagraph]) -> Dict[str, int]:
    """How many chosen paragraphs carried each advisory quality flag."""
    counts: Dict[str, int] = {}
    for outcome in outcomes:
        for flag in outcome.quality.get("flags", ()):
            counts[flag] = counts.get(flag, 0) + 1
    return dict(sorted(counts.items()))


def humanize_guided(
    text: str,
    config: Optional[GuidedConfig] = None,
    backend: Optional[llm_mod.Backend] = None,
    detector: Any = None,
    guide: Any = None,
    on_event: Optional[Callable[[ProgressEvent], None]] = None,
) -> GuidedResult:
    """Blocking wrapper over `stream()`. Same arguments, same guarantees."""
    final: Optional[GuidedResult] = None
    for ev in stream(
        text, config=config, backend=backend, detector=detector, guide=guide
    ):
        if on_event is not None:
            on_event(ev)
        if ev.result_object is not None:
            final = ev.result_object
    if final is None:  # pragma: no cover - stream always ends with finalize
        raise RuntimeError("guided decoding produced no result")
    return final
